<?php

namespace App\Console\Commands;

use App\Jobs\BuildBackupJob;
use App\Models\Backup;
use Illuminate\Console\Command;

/**
 * گرفتنِ بکاپِ کاملِ سیستم بدونِ دخالتِ آدم (R43).
 *
 * ─── چه چیزی کم بود ────────────────────────────────────────────────────────
 * ⚠️ سازوکارِ بکاپ کامل بود — ساخت، رمزنگاری (R20)، بازیابی، و هرسِ دوره‌ای —
 * ولی **هیچ‌کدام خودکار شروع نمی‌شدند**. تنها راهِ ساختنِ بکاپ، فشردنِ دکمه‌ای
 * در پنلِ سوپرادمین بود.
 *
 * یعنی سامانه‌ای که هر شب بکاپ‌های قدیمی را هرس می‌کرد، هرگز بکاپِ تازه‌ای
 * نمی‌ساخت. اگر کسی چند ماه دکمه را نمی‌زد، `backups:prune` بی‌خبر آخرین
 * نسخه‌ها را هم نگه می‌داشت ولی هیچ‌کدام تازه نبودند — و روزِ حادثه معلوم
 * می‌شد تازه‌ترین نسخه مالِ ماه‌ها پیش است.
 *
 * ─── چرا فقط بکاپِ کاملِ سیستم ───────────────────────────────────────────────
 * بکاپِ کامل همه‌ی جدول‌های هر مجتمع را در خود دارد، پس گرفتنِ بکاپِ جداگانه
 * برای تک‌تکِ مجتمع‌ها یعنی همان داده چند بار روی دیسک بنشیند. بکاپِ
 * مجتمعی همان کاربردِ قبلی‌اش را دارد: وقتی مدیرِ یک مجتمع پیش از تغییری
 * بزرگ، نسخه‌ی خودش را می‌خواهد.
 */
class RunScheduledBackup extends Command
{
    protected $signature = 'backups:run {--note= : یادداشتی که روی رکورد می‌نشیند}';

    protected $description = 'ساختِ بکاپِ کاملِ سیستم (برای زمان‌بند)';

    public function handle(): int
    {
        $backup = Backup::create([
            'complex_id' => null,
            'type' => 'full',
            'status' => 'pending',
            'disk' => 'local',
            'note' => $this->option('note') ?: 'بکاپ خودکار روزانه',
            // ⚠️ عمداً خالی: هیچ کاربری این را نساخته و نسبت‌دادنش به
            // سوپرادمین یعنی در سیاهه‌ی ممیزی کاری به نامِ کسی بخورد که
            // انجامش نداده
            'created_by' => null,
        ]);

        /*
         * ⚠️ ساخت در صف انجام می‌شود، نه همین‌جا.
         *
         * بکاپِ سیستم همه‌ی ردیف‌های ~۱۸ جدول را در حافظه می‌خواند. اجرای
         * هم‌زمانش با بقیه‌ی کارهای زمان‌بند می‌تواند حافظه‌ی PHP را تمام کند
         * و کارهای دیگرِ همان اجرا را هم با خود پایین بکشد.
         */
        BuildBackupJob::dispatch($backup->id);

        $this->info("بکاپِ خودکار در صف قرار گرفت (شناسه: {$backup->id}).");

        return self::SUCCESS;
    }
}
