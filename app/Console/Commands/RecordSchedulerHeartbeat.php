<?php

namespace App\Console\Commands;

use App\Services\Health\HealthReport;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Cache;

/**
 * ثبتِ اینکه زمان‌بند زنده است (R43).
 *
 * ─── چرا این کوچک‌ترین دستورِ پروژه، مهم‌ترینِ این مرحله است ─────────────────
 * ⚠️ خاموش‌بودنِ cron **هیچ نشانه‌ای بیرون نمی‌دهد**. هیچ خطایی، هیچ ۵۰۰ای،
 * هیچ لاگی. سایت کاملاً سالم به نظر می‌رسد و کاربر هیچ فرقی حس نمی‌کند.
 * فقط بکاپ گرفته نمی‌شود، اشتراکِ منقضی بسته نمی‌شود، `failed_jobs` بی‌صدا
 * بزرگ می‌شود و جدولِ سنجه‌ها بی‌مرز رشد می‌کند.
 *
 * چنین خرابی‌ای می‌تواند **ماه‌ها** دیده نشود — و درست همان روزی فهمیده
 * می‌شود که به آخرین بکاپ نیاز داری و می‌بینی آخرین بکاپ مالِ نود روز پیش
 * است. یک خط نوشتن در کش، جلوی همان روز را می‌گیرد.
 *
 * ⚠️ خواننده‌ی این ضربان عمداً **مسیرِ HTTP** است، نه دستورِ `health:check`.
 * اگر دستوری که از خودِ cron اجرا می‌شود آن را بخواند، هرگز کهنه نمی‌بیندش:
 * زنده‌بودنِ cron پیش‌شرطِ اجرای خودش است. تنها ناظری که می‌تواند مرگِ cron
 * را ببیند، ناظری است که بیرونِ cron ایستاده.
 */
class RecordSchedulerHeartbeat extends Command
{
    protected $signature = 'health:heartbeat';

    protected $description = 'ثبتِ زمانِ آخرین اجرای موفقِ زمان‌بند';

    public function handle(): int
    {
        /*
         * مدتِ نگه‌داری چند برابرِ آستانه‌ی کهنگی است.
         *
         * اگر درست به اندازه‌ی آستانه بود، انقضای کش و کهنگیِ واقعی از هم
         * قابلِ تفکیک نبودند — هر دو «کلید نیست» می‌شدند و نمی‌شد فهمید
         * زمان‌بند مرده یا فقط کلید منقضی شده. با پنجره‌ی بلندتر، «کلید نیست»
         * یعنی واقعاً مدت‌هاست خبری نیست.
         */
        Cache::put(
            HealthReport::HEARTBEAT_KEY,
            now()->toIso8601String(),
            HealthReport::SCHEDULER_STALE_MINUTES * 60 * 6,
        );

        return self::SUCCESS;
    }
}
