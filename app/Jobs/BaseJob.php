<?php

namespace App\Jobs;

use App\Services\ErrorRecorder;
use Illuminate\Contracts\Queue\ShouldQueue;
use Illuminate\Foundation\Queue\Queueable;
use Throwable;

/**
 * پیش‌فرض‌های مشترکِ همه‌ی Jobها.
 *
 * ─── چرا کلاسِ پایه و نه تکرار در هر Job ───────────────────────────────────
 * `tries`/`backoff`/`timeout` اگر در هر Job جدا نوشته شوند، اولین Jobی که
 * یکی‌شان را جا بیندازد **بی‌نهایت تلاش می‌کند** یا **برای همیشه معلق
 * می‌ماند** — و هیچ‌کدام خطا نمی‌دهند، فقط صف را بند می‌آورند.
 *
 * ─── چرا `failed()` به `ErrorRecorder` وصل است ─────────────────────────────
 * Jobِ شکست‌خورده در جدولِ `failed_jobs` می‌نشیند که هیچ‌کس نگاهش نمی‌کند.
 * با این اتصال، همان شکست در صفحه‌ی «پایش و تحلیل» (R8) کنارِ بقیه‌ی خطاها
 * دیده می‌شود — یعنی جایی که ادمین واقعاً نگاه می‌کند.
 */
abstract class BaseJob implements ShouldQueue
{
    use Queueable;

    /**
     * سه تلاش، نه بیشتر.
     *
     * خطای گذرا معمولاً در تلاشِ دوم حل می‌شود؛ چیزی که سه بار شکست خورده
     * احتمالاً باگ است و تلاشِ چهارم فقط صف را مشغول می‌کند.
     */
    public int $tries = 3;

    /**
     * فاصله‌ی فزاینده بین تلاش‌ها (ثانیه).
     *
     * همان منطقِ لایه‌ی HTTP در R5: اگر سرویسِ بیرونی زیرِ فشار است، کوبیدنِ
     * دوباره‌اش بلافاصله وضع را بدتر می‌کند.
     */
    public array $backoff = [10, 60, 180];

    /**
     * سقفِ زمانِ اجرا.
     *
     * بدونِ این، یک Jobِ گیرکرده (اتصالِ نیمه‌بازِ شبکه، کوئریِ بی‌پایان)
     * کارگر را برای همیشه اشغال می‌کند و بقیه‌ی صف پشتش می‌ماند.
     */
    public int $timeout = 300;

    /**
     * پس از این مدت (ثانیه) دیگر تلاش نشود.
     *
     * برای کاری که نتیجه‌اش کهنه می‌شود، تلاشِ دیرهنگام بی‌فایده است.
     *
     * ⚠️ نامش عمداً `retryUntil` **نیست**.
     *
     * لاراول اگر ویژگیِ `retryUntil` ببیند، مقدارش را یک **timestamp** فرض
     * می‌کند نه یک بازه. با نامِ `retryUntil` و مقدارِ ۳۶۰۰، هر Job تاریخِ
     * انقضایش سالِ ۱۹۷۰ می‌شد و کارگر پیش از اولین اجرا آن را با
     * «attempted too many times» شکست‌خورده اعلام می‌کرد — بی‌آنکه `handle()`
     * حتی یک بار صدا زده شود.
     *
     * این را تستِ صفِ `sync` نمی‌گیرد؛ فقط با کارگرِ واقعی دیده شد.
     */
    public int $retryForSeconds = 3600;

    /** لاراول این متد را برای تعیینِ مهلتِ نهایی صدا می‌زند. */
    public function retryUntil(): \DateTimeInterface
    {
        return now()->addSeconds($this->retryForSeconds);
    }

    /**
     * پس از آخرین تلاشِ ناموفق.
     *
     * زیرکلاس‌ها معمولاً این را بازنویسی می‌کنند تا وضعیتِ رکوردِ مربوطه را
     * هم `failed` کنند — ولی باید `parent::failed()` را صدا بزنند تا ثبتِ
     * مرکزی از دست نرود.
     */
    public function failed(?Throwable $exception): void
    {
        if ($exception) {
            ErrorRecorder::fromException($exception, static::class, 'QUEUE');
        }
    }
}
