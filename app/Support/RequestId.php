<?php

namespace App\Support;

/**
 * شناسه‌ی یکتای هر درخواست (R63).
 *
 * ─── 🔴 چه چیزی نبود ───────────────────────────────────────────────────────
 * ⚠️ اندازه‌گیری شد: هیچ شناسه‌ی درخواستی در کلِ سامانه وجود نداشت. یعنی
 * وقتی کاربر زنگ می‌زد و می‌گفت «پرداختم خراب شد»، تنها راهِ پیداکردنِ آن
 * درخواست، گشتن در `storage/logs` بر اساسِ **حدسِ زمان** بود — و در
 * ساعتِ شلوغ، ده‌ها درخواستِ مشابه در همان دقیقه هست.
 *
 * حالا همان کاربر یک کدِ کوتاه می‌خواند و ما دقیقاً همان درخواست را
 * می‌بینیم: لاگ‌هایش، کارِ صفش، و ردیفِ خطایش.
 *
 * ─── ⚠️ چرا UUID نه ────────────────────────────────────────────────────────
 * `9f8a2c1e-…` را نمی‌شود پای تلفن خواند. این کد قرار است **با صدای
 * انسان** منتقل شود، پس:
 *
 *   • حروفِ بزرگ، بدونِ خط تیره‌ی داخلی جز یکی
 *   • بدونِ `I` `L` `O` `U` و بدونِ `0` `1` — که با هم اشتباه می‌شوند
 *   • ده نویسه در دو گروهِ پنج‌تایی: «RTKMB - 7XQ9F»
 *
 * ⚠️ `U` هم حذف شده تا هیچ کلمه‌ی ناخواسته‌ای ساخته نشود.
 *
 * فضای حالت با ۱۰ نویسه از الفبای ۳۱ حرفی حدود ۸×۱۰¹⁴ است — برای
 * تشخیصِ یکتاییِ عملی در بازه‌ی نگه‌داریِ لاگ کاملاً کافی، و این
 * شناسه‌ی امنیتی نیست که به حدس‌ناپذیریِ رمزنگارانه نیاز داشته باشد.
 */
class RequestId
{
    public const HEADER = 'X-Request-Id';

    /**
     * کلیدی که شناسه با آن داخلِ payloadِ کارِ صف سفر می‌کند.
     *
     * ⚠️ پیشوندِ `_` عمدی است: payloadِ کار متعلق به لاراول است و کلیدِ
     * بی‌پیشوند می‌تواند روزی با کلیدِ خودِ فریم‌ورک تصادم کند.
     */
    public const PAYLOAD_KEY = '_requestId';

    /** ⚠️ بدونِ I، L، O، U، صفر و یک — تا خواندنش پای تلفن مبهم نباشد. */
    private const ALPHABET = '23456789ABCDEFGHJKMNPQRSTVWXYZ';

    private static ?string $current = null;

    /**
     * شناسه‌ی این درخواست (یا این کارِ صف).
     *
     * ⚠️ تنبل ساخته می‌شود: اگر هیچ‌کس نپرسد، هیچ هزینه‌ای ندارد. ولی
     * همین‌که یک بار پرسیده شد، تا پایانِ همان پردازه ثابت می‌ماند — وگرنه
     * دو خطِ لاگِ یک درخواست دو شناسه‌ی متفاوت می‌گرفتند و کلِ هدف از بین
     * می‌رفت.
     */
    public static function current(): string
    {
        return self::$current ??= self::generate();
    }

    /**
     * نشاندنِ شناسه‌ی مشخص.
     *
     * دو مصرف‌کننده دارد: میدل‌ور (که شناسه‌ی ورودی را می‌پذیرد یا تازه
     * می‌سازد) و کارگرِ صف (که شناسه‌ی درخواستِ سازنده‌ی کار را برمی‌گرداند).
     */
    public static function set(?string $id): void
    {
        self::$current = self::acceptable($id) ? $id : self::generate();
    }

    /** برای تست و برای مرزِ بینِ دو کارِ صف. */
    public static function forget(): void
    {
        self::$current = null;
    }

    /**
     * آیا این مقدارِ ورودی قابلِ پذیرش است؟
     *
     * 🔴 **این تابع یک محافظِ امنیتی است، نه اعتبارسنجیِ سلیقه‌ای.**
     *
     * شناسه‌ی ورودی از هدرِ HTTP می‌آید، یعنی کاملاً در اختیارِ فرستنده
     * است. اگر بی‌بررسی در لاگ بنشیند، مهاجم می‌تواند خطِ جعلیِ لاگ
     * بسازد (`\n[2026-01-01] ...`) یا فایلِ لاگ را با یک مقدارِ چندمگابایتی
     * پر کند.
     *
     * پس فقط دقیقاً همان قالبی پذیرفته می‌شود که خودمان می‌سازیم؛ هر چیزِ
     * دیگری بی‌سروصدا با یک شناسه‌ی تازه جایگزین می‌شود.
     */
    public static function acceptable(?string $id): bool
    {
        return is_string($id) && preg_match('/^[2-9A-HJ-NP-Z]{5}-[2-9A-HJ-NP-Z]{5}$/', $id) === 1;
    }

    private static function generate(): string
    {
        $alphabet = self::ALPHABET;
        $max = strlen($alphabet) - 1;

        $out = '';

        for ($i = 0; $i < 10; $i++) {
            if ($i === 5) {
                $out .= '-';
            }

            $out .= $alphabet[random_int(0, $max)];
        }

        return $out;
    }
}
