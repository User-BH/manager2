<?php

namespace App\Support;

use Illuminate\Support\Facades\Cache;

/**
 * شناسه‌ی همین ساختِ فرانت (R61).
 *
 * ─── 🔴 مسئله‌ای که حل می‌کند: Mixed App Versions ──────────────────────────
 * ⚠️ کاربری که تبِ داشبورد را باز گذاشته، جاوااسکریپتِ **دیروز** را در
 * حافظه دارد. ما امروز استقرار می‌دهیم. از این لحظه، آن تب با APIی حرف
 * می‌زند که کدش عوض شده — و هیچ‌کس، نه کاربر و نه ما، خبر ندارد.
 *
 * خرابی‌اش هم معمولاً «خطا» نیست؛ **رفتارِ اشتباه** است: فیلدی که دیگر
 * نیست `undefined` می‌شود، ستونی خالی می‌ماند، دکمه‌ای کاری نمی‌کند. و
 * چون خطایی ثبت نمی‌شود، تنها نشانه‌اش شکایتِ کاربر است.
 *
 * ─── چرا هشِ manifest و نه شماره‌ی نسخه یا کامیت ───────────────────────────
 * چیزی می‌خواهیم که **دقیقاً وقتی فرانت عوض می‌شود** عوض شود:
 *
 *   • شماره‌ی نسخه‌ی دستی → یادِ کسی می‌رود بالا ببرد
 *   • هشِ کامیت → با هر تغییرِ بک‌اند هم عوض می‌شود، پس تبِ سالمِ کاربر
 *     را بی‌دلیل به «نسخه‌ی تازه» هشدار می‌دهد
 *   • `manifest.json`ِ Vite ← نامِ فایل‌ها هش دارند، پس این فایل دقیقاً و
 *     فقط وقتی عوض می‌شود که خروجیِ ساخت عوض شده باشد
 *
 * ─── ⚠️ و اگر manifest نباشد ───────────────────────────────────────────────
 * در محیطِ توسعه (سرورِ Vite) یا پیش از اولین `npm run build` این فایل
 * وجود ندارد. آن‌وقت مقدارِ ثابتِ `dev` برمی‌گردد: هیچ‌وقت با خودش فرق
 * نمی‌کند، پس هشدارِ کاذب نمی‌دهد.
 */
class AppBuild
{
    /** ⚠️ مقدارِ ثابتِ حالتِ توسعه؛ عمداً هرگز عوض نمی‌شود. */
    public const DEV = 'dev';

    private const CACHE_KEY = 'app-build-id';

    /**
     * شناسه‌ی ساختِ فعلی.
     *
     * ⚠️ در هر درخواست خوانده می‌شود (هم در هدرِ API، هم در HTML)، پس
     * `filemtime`+`md5_file` نباید هر بار انجام شود. کش با کلیدِ ثابت و
     * عمرِ کوتاه: پس از استقرار حداکثر یک دقیقه طول می‌کشد تا مقدارِ تازه
     * دیده شود، که در برابرِ خواندنِ فایل در هر درخواست معامله‌ی درستی است.
     */
    public static function current(): string
    {
        return (string) Cache::remember(
            self::CACHE_KEY,
            now()->addMinute(),
            fn () => self::compute(),
        );
    }

    /** بدونِ کش — برای تست و برای `config:cache`ِ پس از استقرار. */
    public static function compute(): string
    {
        $manifest = public_path('build/manifest.json');

        if (! is_file($manifest)) {
            return self::DEV;
        }

        return substr((string) md5_file($manifest), 0, 12);
    }

    /** پس از استقرار، تا کشِ یک‌دقیقه‌ای منقضی نشده، دستی خالی می‌شود. */
    public static function forget(): void
    {
        Cache::forget(self::CACHE_KEY);
    }
}
