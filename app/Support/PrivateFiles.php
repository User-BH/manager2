<?php

namespace App\Support;

use Illuminate\Contracts\Filesystem\Filesystem;
use Illuminate\Support\Facades\Storage;

/**
 * تنها درِ ورود به فایل‌های خصوصیِ کاربران (R45).
 *
 * ─── مشکلی که اندازه‌گیری شد ────────────────────────────────────────────────
 * ⚠️ هجده نقطه در برنامه `Storage::disk('local')` را **هاردکد** کرده بودند:
 * رسیدِ پرداخت، تصویرِ آگهی، فایلِ بکاپ و PDFهای تولیدشده.
 *
 * تا وقتی سرور یکی است این کار می‌کند. با دو گره، همان لحظه می‌شکند:
 *
 *   ساکن رسید را آپلود می‌کند  → روی دیسکِ گره‌ی A می‌نشیند
 *   مدیر می‌خواهد ببیندش       → درخواست به گره‌ی B می‌رسد → ۴۰۴
 *
 * و این خرابی **بی‌صدا و پراکنده** است: بسته به اینکه متعادل‌کننده‌ی بار
 * کدام گره را انتخاب کند، گاهی کار می‌کند و گاهی نه. یعنی بدترین نوعِ باگ
 * برای رفع‌عیب.
 *
 * ─── و کلیدِ تنظیماتش از قبل بود، ولی مرده ─────────────────────────────────
 * ⚠️ `.env` کلیدِ `FILESYSTEM_DISK` دارد، ولی چون کد نامِ دیسک را هاردکد
 * کرده بود، عوض‌کردنش **هیچ اثری نداشت**. کسی می‌توانست
 * `FILESYSTEM_DISK=s3` بگذارد، مطمئن شود کار کرده، و فایل‌ها همچنان روی
 * دیسکِ محلی بنشینند.
 *
 * ─── چرا یک کلاس و نه صدا زدنِ `config()` در هجده جا ────────────────────────
 * یک جا برای مستندکردنِ قرارداد، و مهم‌تر: یک الگوی قابلِ‌جستجو. تستِ
 * `ScalabilityTest` مطمئن می‌شود کسی دوباره `disk('local')` را در کدِ
 * برنامه ننویسد — چیزی که با `config()`های پراکنده قابلِ اجرا نبود.
 */
class PrivateFiles
{
    /**
     * دیسکی که فایل‌های خصوصیِ کاربران روی آن می‌نشینند.
     *
     * پیش‌فرض `local` است تا نصبِ تک‌سروری بدونِ هیچ تنظیمی کار کند؛ برای
     * چند گره کافی است `PRIVATE_DISK=s3` (یا هر ذخیره‌سازِ اشتراکیِ دیگر)
     * گذاشته شود و هیچ خطی از کد عوض نمی‌شود.
     */
    public static function disk(): Filesystem
    {
        return Storage::disk(self::name());
    }

    /** نامِ دیسک — جایی که باید در ستونِ `disk` رکورد ذخیره شود. */
    public static function name(): string
    {
        $disk = config('filesystems.private');

        return is_string($disk) && $disk !== '' ? $disk : 'local';
    }
}
