<?php

namespace App\Support;

use Illuminate\Contracts\Encryption\DecryptException;
use Illuminate\Support\Facades\Crypt;
use RuntimeException;

/**
 * رمزگذاریِ تحمل‌پذیرِ مقادیرِ حساسِ داخلِ دیتابیس (R55 / رفعِ M-01).
 *
 * ─── مشکلی که حل می‌کند ────────────────────────────────────────────────────
 * ⚠️ `complexes.gateway_config` و `settings.sms_config` **متنِ ساده** بودند.
 * یعنی رمزِ درگاهِ بانکی و کلیدِ پنلِ پیامک، خام، در دیتابیس. این
 * آسیب‌پذیریِ از راه دور نیست — خواندنِ دیتابیس لازم دارد — ولی
 * **تشدیدکننده** است: هر نشتِ دیتابیس مستقیماً به اعتبارنامه‌ی زنده‌ی بانکی
 * تبدیل می‌شود.
 *
 * ─── چرا «تحمل‌پذیر» ───────────────────────────────────────────────────────
 * ⚠️ اگر کست را یک‌شبه به `encrypted` عوض کنیم، **ردیف‌های موجود** که متنِ
 * ساده‌اند هنگامِ خواندن استثنا می‌دهند و پرداختِ زنده می‌شکند. بدتر:
 * مهاجرتی که وسطِ کار قطع شود، نیمی رمزشده و نیمی ساده جا می‌گذارد.
 *
 * پس خواندن هر دو شکل را می‌پذیرد و نوشتن **همیشه** رمز می‌کند. با این
 * ترتیب، قطعِ میانیِ مهاجرت بی‌خطر است.
 *
 * ─── حالتِ سومی که نباید بی‌صدا رد شود ─────────────────────────────────────
 * ⚠️ اگر مقدار **نه** رمزگشایی شود و **نه** JSONِ معتبر باشد، تقریباً
 * همیشه یک معنا دارد: `APP_KEY` عوض شده است.
 *
 * برگرداندنِ آرایه‌ی خالی در آن حالت یعنی «درگاهی تنظیم نشده» — سامانه به
 * پرداختِ رسیدی برمی‌گردد و **هیچ‌کس نمی‌فهمد چرا**. پس عمداً استثنا
 * پرتاب می‌شود، با پیامی که دقیقاً می‌گوید چه اتفاقی افتاده و چه باید کرد.
 * شکستِ بلند بهتر از خرابیِ خاموش است.
 */
class SecretValue
{
    /** مقدار را برای ذخیره در دیتابیس رمز می‌کند. */
    public static function protect(string $plain): string
    {
        return Crypt::encryptString($plain);
    }

    /**
     * مقدارِ ذخیره‌شده را برمی‌گرداند — چه رمزشده باشد چه متنِ سادهٔ قدیمی.
     *
     * @param  string  $context  نامی که در پیامِ خطا می‌آید، تا معلوم باشد کدام مقدار
     */
    public static function reveal(string $stored, string $context): string
    {
        if ($stored === '') {
            return '';
        }

        try {
            return Crypt::decryptString($stored);
        } catch (DecryptException) {
            // شاید ردیفِ قدیمیِ متنِ ساده باشد؛ پایین بررسی می‌شود
        }

        if (self::looksLikeJson($stored)) {
            return $stored;
        }

        throw new RuntimeException(
            "مقدارِ «{$context}» نه رمزگشایی شد و نه دادهٔ سالمِ قدیمی است. "
            .'محتمل‌ترین علت این است که APP_KEY عوض شده باشد؛ با کلیدِ تازه '
            .'هیچ مقدارِ رمزشده‌ای خوانده نمی‌شود. رویهٔ چرخشِ کلید در '
            .'docs/SECRETS.md آمده است.'
        );
    }

    /**
     * آیا این مقدار از قبل رمز شده است؟
     *
     * ⚠️ مهاجرت به این نیاز دارد تا **بی‌خطر تکرارپذیر** باشد: اجرای
     * دوباره‌اش نباید مقدارِ رمزشده را دوباره رمز کند.
     */
    public static function isProtected(string $stored): bool
    {
        if ($stored === '') {
            return false;
        }

        try {
            Crypt::decryptString($stored);

            return true;
        } catch (DecryptException) {
            return false;
        }
    }

    /**
     * ⚠️ `json_decode` برای رشته‌ی `"null"` هم `null` می‌دهد.
     *
     * پس فقط نبودنِ خطا سنجیده می‌شود، نه خروجی — وگرنه یک مقدارِ سالم
     * می‌توانست «خراب» تشخیص داده شود.
     */
    private static function looksLikeJson(string $value): bool
    {
        json_decode($value, true);

        return json_last_error() === JSON_ERROR_NONE;
    }
}
