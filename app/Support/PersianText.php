<?php

namespace App\Support;

/**
 * نرمال‌سازی متن فارسی برای تطبیق.
 *
 * بدون این، «کارکرد» و «كاركرد» دو رشته‌ی متفاوت‌اند (ک و ي عربی در برابر
 * فارسی)، «۱۲» با «12» جور نمی‌شود و نیم‌فاصله هر کلمه را دو تکه می‌کند.
 * کاربر ایرانی هر سه شکل را تایپ می‌کند، پس تطبیق باید هر سه را یکی ببیند.
 */
class PersianText
{
    /** نویسه‌های عربی و هم‌شکل که باید به معادل فارسی برگردند. */
    private const CHARACTER_MAP = [
        'ك' => 'ک', 'ﻙ' => 'ک', 'ﻚ' => 'ک',
        'ي' => 'ی', 'ﻱ' => 'ی', 'ﻲ' => 'ی', 'ى' => 'ی',
        'ة' => 'ه', 'ۀ' => 'ه',
        'ؤ' => 'و', 'إ' => 'ا', 'أ' => 'ا', 'آ' => 'ا', 'ٱ' => 'ا',
        'ئ' => 'ی',
    ];

    /** اعراب و نویسه‌های نامرئی که در تطبیق نقشی ندارند. */
    private const REMOVABLE = [
        "\u{064B}", "\u{064C}", "\u{064D}", "\u{064E}", "\u{064F}", "\u{0650}",
        "\u{0651}", "\u{0652}", "\u{0653}", "\u{0654}", "\u{0655}", "\u{0640}",
        "\u{200C}", "\u{200D}", "\u{200E}", "\u{200F}", "\u{FEFF}",
    ];

    private const DIGIT_MAP = [
        '۰' => '0', '۱' => '1', '۲' => '2', '۳' => '3', '۴' => '4',
        '۵' => '5', '۶' => '6', '۷' => '7', '۸' => '8', '۹' => '9',
        '٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4',
        '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9',
    ];

    /**
     * شکل یکدست یک متن برای مقایسه.
     *
     * نیم‌فاصله به فاصله تبدیل نمی‌شود بلکه حذف می‌شود، چون «می‌شود» و
     * «میشود» باید یکی باشند نه «می شود».
     */
    public static function normalize(string $text): string
    {
        $text = mb_strtolower(trim($text));
        $text = strtr($text, self::CHARACTER_MAP);
        $text = strtr($text, self::DIGIT_MAP);
        $text = str_replace(self::REMOVABLE, '', $text);

        // نشانه‌گذاری به فاصله تبدیل می‌شود تا کلمه‌ها از هم جدا بمانند
        $text = preg_replace('/[^\p{L}\p{N}]+/u', ' ', $text) ?? $text;

        return trim(preg_replace('/\s+/', ' ', $text) ?? $text);
    }

    /**
     * واژه‌های معنادار متن.
     *
     * کلمات ربطی و پرتکرار حذف می‌شوند چون در همه‌ی جمله‌ها هستند و اگر
     * بمانند، هر پیامی با هر موضوعی امتیاز می‌گیرد.
     *
     * @return array<int,string>
     */
    public static function tokens(string $text): array
    {
        $stopWords = [
            'و', 'در', 'به', 'از', 'که', 'را', 'با', 'این', 'آن', 'است', 'هست',
            'می', 'برای', 'یک', 'شود', 'شد', 'کرد', 'کنم', 'کنید', 'من', 'ما',
            'شما', 'ایا', 'چه', 'چی', 'چطور', 'چگونه', 'ها', 'های', 'تا', 'هم',
            'اگر', 'یا', 'بر', 'کن', 'بود', 'باشد', 'دارد', 'دارم', 'دارید',
        ];

        $tokens = array_filter(
            explode(' ', self::normalize($text)),
            fn (string $t) => mb_strlen($t) > 1 && ! in_array($t, $stopWords, true),
        );

        return array_values(array_unique($tokens));
    }

    /**
     * واژه‌ها به‌علاوه‌ی جفت‌های چسبیده‌ی مجاور.
     *
     * کاربر «ثبت نام» می‌نویسد ولی کلیدواژه «ثبتنام» است؛ بدون ساختن جفت،
     * پیام به دو واژه‌ی بی‌وزن تجزیه می‌شد و موضوع تشخیص داده نمی‌شد. همین
     * برای «از دست»، «کلمه عبور» و «پیام رسان» هم لازم است.
     *
     * @return array<int,string>
     */
    public static function searchTerms(string $text): array
    {
        $tokens = self::tokens($text);
        $terms = $tokens;

        // جفت‌ها از متنِ نرمال‌شده ساخته می‌شوند نه از توکن‌های فیلترشده،
        // چون واژه‌ی ربطی ممکن است وسط یک عبارت باشد («از دست رفتن»).
        $words = array_values(array_filter(explode(' ', self::normalize($text))));

        for ($i = 0; $i < count($words) - 1; $i++) {
            $terms[] = $words[$i].$words[$i + 1];
        }

        return array_values(array_unique($terms));
    }

    /**
     * درجه‌ی تطبیق دو واژه: ۱ برای یکسان، ۰٫۸ برای هم‌ریشه، ۰ برای بی‌ربط.
     *
     * فارسی چسبان است: «پرداخت»، «پرداختی» و «پرداخت‌ها» یک مفهوم‌اند، پس
     * تطبیق پیشوندی لازم است. ولی نباید هم‌وزنِ تطبیق دقیق باشد: «پشتیبانی»
     * با «پشتیبان» (بکاپ) هم‌ریشه است و اگر امتیاز کامل بگیرد، سوالِ تماس با
     * پشتیبانی به موضوع بکاپ می‌رود — دقیقاً همان اشتباهی که رخ می‌داد.
     */
    public static function similarity(string $token, string $keyword): float
    {
        return self::match($token, $keyword)['score'];
    }

    /**
     * تطبیق، به‌همراهِ **جنسِ** آن.
     *
     * ─── چرا فقط امتیاز کافی نبود ──────────────────────────────────────────
     * امتیازِ تنها نمی‌گوید شواهد از چه جنسی‌اند، و این دو خیلی فرق دارند:
     *
     * • «شارج» ↔ «شارژ» — هم‌طول، یک نویسه فرق. کاربر **همین واژه** را
     *   می‌خواسته و اشتباه تایپ کرده. شاهدِ محکم.
     * • «بازی» ↔ «بازیابی» — «بازی» خودش یک واژه‌ی کاملِ بی‌ربط است که
     *   تصادفاً پیشوندِ واژه‌ی دیگری شده. شاهدِ ضعیف.
     *
     * هر دو با امتیازِ خام «تطبیق» حساب می‌شدند، و همین باعث می‌شد «نتیجه
     * بازی پرسپولیس چی شد» با اطمینان به موضوعِ **بکاپ** برود. حالا
     * `SupportBot` می‌تواند بگوید یک شاهدِ ضعیفِ تنها برای اطمینان کافی
     * نیست.
     *
     * @return array{score:float,kind:'exact'|'typo'|'inflection'|'stem'|'none'}
     */
    public static function match(string $token, string $keyword): array
    {
        if ($token === $keyword) {
            return ['score' => 1.0, 'kind' => 'exact'];
        }

        $shorter = mb_strlen($token) <= mb_strlen($keyword) ? $token : $keyword;
        $longer = $shorter === $token ? $keyword : $token;
        $shortLen = mb_strlen($shorter);
        $extra = mb_strlen($longer) - $shortLen;

        if (str_starts_with($longer, $shorter)) {
            /*
             * ⚠️ **کدام‌طرف بلندتر است** تعیین‌کننده است، نه صرفِ پیشوند بودن:
             *
             * • «هزینه‌ها» ↔ «هزینه» — واژه‌ی کاربر بلندتر است، یعنی همان
             *   کلیدواژه با پسوندِ جمع/صرفی. شاهدِ محکم.
             * • «بازی» ↔ «بازیابی» — واژه‌ی کاربر کوتاه‌تر است، یعنی او
             *   واژه‌ی **دیگری** گفته که تصادفاً پیشوند شده. شاهدِ ضعیف.
             *
             * این تفکیک را اول نداشتم و هر دو را `stem` می‌گرفتم؛ نتیجه‌اش
             * این شد که «هزینه‌ها چقدر است؟» — که خودش یکی از پرسش‌های
             * پیشنهادیِ ماست — بی‌پاسخ ماند.
             */
            $kind = mb_strlen($token) >= mb_strlen($keyword) ? 'inflection' : 'stem';

            /*
             * ریشه‌ی سه‌نویسه‌ای فقط وقتی پذیرفته می‌شود که تفاوت طول کم باشد
             * («امن» با «امنه» بله، «امن» با «امنیتی‌ترین» نه)؛ از چهار نویسه به
             * بالا دست بازتر است.
             */
            if ($shortLen >= 4 && $extra <= 4) {
                return ['score' => 0.8, 'kind' => $kind];
            }

            if ($shortLen === 3 && $extra <= 2) {
                return ['score' => 0.7, 'kind' => $kind];
            }

            return ['score' => 0.0, 'kind' => 'none'];
        }

        /*
         * غلطِ املایی: نویسه‌های همسایه‌ی کیبورد («ج» و «ژ»)، «ح/ه»، «ت/ط» و
         * جاافتادنِ یک حرف. اینجا اختلافِ طول باید کم باشد، وگرنه هر دو
         * واژه‌ی کوتاهی به هم می‌چسبند.
         */
        if ($extra > 1 || $shortLen < 4) {
            return ['score' => 0.0, 'kind' => 'none'];
        }

        /*
         * ⚠️ فقط **یک** غلط، و این حد عمدی است.
         *
         * ردیفِ «دو غلط در واژه‌های بلند» را اول گذاشتم و پس گرفتم: «اطلاعات»
         * و «اطلاعیه» هر دو هفت‌نویسه‌اند و دقیقاً دو ویرایش فاصله دارند،
         * ولی دو واژه‌ی کاملاً متفاوتِ پرکاربردند. نتیجه این شد که «اطلاعات
         * شخصی ما محفوظه؟» از موضوعِ **امنیت** به **پیام‌رسان** رفت. فارسی
         * از این جفت‌ها زیاد دارد؛ در فاصله‌ی دو، احتمالِ «واژه‌ی دیگر» از
         * احتمالِ «غلطِ تایپی» بیشتر است.
         *
         * امتیازِ ‎۰٫۸۵ از هم‌ریشه (‎۰٫۸) بالاتر است و این هم عمدی است: غلطِ
         * تایپی یعنی کاربر **همین واژه** را می‌خواسته، ولی هم‌ریشه یعنی
         * واژه‌ی او واژه‌ی دیگری است که اتفاقاً پیشوند شده.
         */
        return self::distance($token, $keyword) === 1
            ? ['score' => 0.85, 'kind' => 'typo']
            : ['score' => 0.0, 'kind' => 'none'];
    }

    /**
     * فاصله‌ی ویرایشیِ دو رشته، شمرده بر حسبِ **نویسه** نه بایت.
     *
     * ⚠️ `levenshtein()`ِ خودِ PHP بایتی است و برای فارسی بی‌معناست: هر حرفِ
     * فارسی دو بایت است، پس «شارژ» و «شارج» از دیدِ آن دو بایت فرق دارند نه
     * یکی، و آستانه‌گذاری روی چنین عددی نتیجه‌ی تصادفی می‌دهد.
     */
    public static function distance(string $a, string $b): int
    {
        $x = mb_str_split($a);
        $y = mb_str_split($b);
        $n = count($y);

        // فقط یک ردیف نگه داشته می‌شود؛ ماتریسِ کامل اینجا لازم نیست
        $previous = range(0, $n);

        foreach ($x as $i => $charA) {
            $current = [$i + 1];

            foreach ($y as $j => $charB) {
                $current[$j + 1] = min(
                    $previous[$j + 1] + 1,          // حذف
                    $current[$j] + 1,               // درج
                    $previous[$j] + ($charA === $charB ? 0 : 1), // جایگزینی
                );
            }

            $previous = $current;
        }

        return $previous[$n];
    }
}
