<?php

namespace App\Enums;

use App\Models\User;

/**
 * حالتِ حسابِ کاربر — پنجمین حالتِ داشبورد (R21).
 *
 * ─── چرا نقشِ تازه اضافه نشد ───────────────────────────────────────────────
 * برنامه‌ی کار از «نقشِ بازدیدکننده» حرف می‌زد. به‌جایش این حالت از **واقعیت**
 * مشتق می‌شود: کاربری که به هیچ مجتمعی وصل نیست، در حالتِ اولیه است.
 *
 * دلیلش این است که نقش و واقعیت می‌توانند از هم جدا بیفتند. اگر نقشِ
 * `visitor` وجود داشت، هر جایی که کاربر به مجتمعی وصل می‌شود (پذیرشِ دعوت،
 * افزودن توسط مدیر، خرید اشتراک) باید یادش می‌ماند نقش را هم عوض کند — و
 * روزی یکی یادش نمی‌رفت. آن‌وقت کاربری با مجتمع ولی نقشِ بازدیدکننده داشتیم
 * که هیچ‌کس نمی‌فهمید چرا چیزی نمی‌بیند.
 *
 * `complex_id === null` نمی‌تواند دروغ بگوید: یا وصل است یا نیست.
 */
enum AccountState: string
{
    /** ثبت‌نام کرده، ولی نه خریده و نه مدیری اضافه‌اش کرده. */
    case Initial = 'initial';

    /** به یک مجتمع وصل است (ساکن، مالک یا مدیرِ مجتمع). */
    case Member = 'member';

    /** ادمینِ کل سامانه. */
    case Platform = 'platform';

    public static function of(User $user): self
    {
        if ($user->role === UserRole::SuperAdmin) {
            return self::Platform;
        }

        return $user->complex_id === null ? self::Initial : self::Member;
    }

    /**
     * آیا این حساب اجازه‌ی هیچ نوشتنی روی داده‌ی مجتمع دارد؟
     *
     * حالتِ اولیه فقط‌خواندنی است: چیزی برای نوشتن ندارد (به هیچ مجتمعی وصل
     * نیست) و اجازه‌ی نوشتن فقط سطحِ حمله اضافه می‌کند.
     */
    public function canWrite(): bool
    {
        return $this !== self::Initial;
    }

    public function label(): string
    {
        return match ($this) {
            self::Initial => 'حساب اولیه',
            self::Member => 'عضو مجتمع',
            self::Platform => 'ادمین کل',
        };
    }
}
