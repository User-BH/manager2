<?php

namespace App\Enums;

/**
 * نوعِ مجتمع: مسکونی یا تجاری (R67).
 *
 * ─── 🔴 تصمیمِ بنیادیِ این مرحله ────────────────────────────────────────────
 * نوع روی **مجتمع** می‌نشیند، نه روی **واحد**.
 *
 * این پرسشِ باز بود و پاسخش کلِ طراحیِ Schema را تعیین می‌کرد: اگر یک
 * مجتمع می‌توانست هم‌زمان طبقاتِ تجاری و مسکونی داشته باشد، نوع باید روی
 * واحد می‌نشست و آن‌وقت هر محاسبه‌ی مالی باید ترکیبِ دو نوع را می‌فهمید.
 *
 * ⚠️ پاسخِ کارفرما صریح بود: **یک مجتمع یا مسکونی است یا تجاری، هرگز هر
 * دو.** پس نوع خاصیتِ خودِ مجتمع است و همه‌ی واحدهایش از آن پیروی می‌کنند.
 *
 * ─── ⚠️ و تفاوتِ واقعی چیست ─────────────────────────────────────────────────
 * باز هم طبقِ تصمیمِ صریحِ کارفرما: **تعرفه‌ی پلن‌های ساکنا**. یعنی همان
 * قابلیت‌ها با قیمتِ متفاوت برای مجتمعِ تجاری.
 *
 * 🔴 هر تفاوتِ دیگری (فرمولِ شارژ بر مبنای متراژ، مفهومِ «کسب‌وکار» به‌جای
 * «مستأجر»، دوره‌ی قرارداد) **عمداً ساخته نشده** — چون گفته نشده بود.
 * ساختنِ منطقِ مالی بر پایه‌ی حدس، در سامانه‌ای که پولِ واقعیِ ساکنین را
 * جابه‌جا می‌کند، بدترین نوعِ ابتکار است. فهرستشان در `docs/COMPLEX_TYPES.md`
 * به‌عنوان پرسشِ باز نوشته شده.
 */
enum ComplexType: string
{
    case Residential = 'residential';

    case Commercial = 'commercial';

    /** پیش‌فرضِ امن: هر مجتمعی که پیش از R67 ساخته شده مسکونی است. */
    public static function default(): self
    {
        return self::Residential;
    }

    public function label(): string
    {
        return match ($this) {
            self::Residential => 'مسکونی',
            self::Commercial => 'تجاری',
        };
    }

    /**
     * آنچه ساکنِ یک واحد نامیده می‌شود.
     *
     * ⚠️ این «فقط تغییرِ Label» نیست، چون از **داده** مشتق می‌شود نه از
     * رشته‌ی ثابت در کد. تفاوتش دقیقاً همین است: افزودنِ نوعِ سوم روزی
     * یک‌جا انجام می‌شود، نه با گشتنِ دنبالِ کلمه‌ی «ساکن» در صد فایل.
     */
    public function occupantLabel(): string
    {
        return match ($this) {
            self::Residential => 'ساکن',
            self::Commercial => 'کسب‌وکار',
        };
    }

    /** جمعِ همان واژه. */
    public function occupantPluralLabel(): string
    {
        return match ($this) {
            self::Residential => 'ساکنین',
            self::Commercial => 'کسب‌وکارها',
        };
    }

    public function unitLabel(): string
    {
        return match ($this) {
            self::Residential => 'واحد',
            self::Commercial => 'واحد تجاری',
        };
    }

    /** @return array<int, string> */
    public static function values(): array
    {
        return array_column(self::cases(), 'value');
    }
}
