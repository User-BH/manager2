<?php

namespace App\Models\Concerns;

use App\Exceptions\DomainException;
use Illuminate\Database\Eloquent\Model;

/**
 * رکوردی که پس از ثبت نه ویرایش می‌شود نه حذف (R51).
 *
 * ─── چرا دفترِ مالی باید تغییرناپذیر باشد ───────────────────────────────────
 * ⚠️ دفتری که بشود ردیفش را عوض کرد، دفتر نیست. کلِ ارزشِ
 * `wallet_transactions` این است که بتوان پرسید «چرا موجودیِ این کاربر
 * ۵۰۰ هزار تومان است؟» و پاسخِ قابلِ‌اتکا گرفت. اگر ردیفی قابلِ ویرایش
 * باشد، آن پاسخ فقط تا ویرایشِ بعدی معتبر است.
 *
 * ─── راهِ درستِ اصلاح ───────────────────────────────────────────────────────
 * اشتباه با **ردیفِ معکوس** جبران می‌شود، نه با پاک‌کردنِ ردیفِ اشتباه. این
 * همان کاری است که حسابداری قرن‌هاست می‌کند: سندِ اشتباه می‌ماند و سندِ
 * برگشتی کنارش می‌نشیند، تا تاریخچه دست‌نخورده بماند.
 *
 * ─── چرا در سطحِ مدل و نه فقط قاعده‌ی تیمی ───────────────────────────────────
 * «هیچ‌وقت ردیفِ دفتر را حذف نکن» یک قاعده است که یادش می‌رود. این کد
 * همان قاعده را **اجرا** می‌کند: هر تلاشی برای ویرایش یا حذف، استثنای
 * روشن می‌دهد.
 *
 * ─── دو لایه، چون یک لایه کافی نبود ───────────────────────────────────────
 * 🔴 رویدادهای زیر فقط مسیرِ **نمونهٔ مدل** را می‌بندند. کاوشِ فاز ۱ نشان
 * داد به‌روزرسانیِ انبوه رویدادِ مدل شلیک نمی‌کند و از تور رد می‌شود:
 *
 *     WalletTransaction::where(...)->update([...])   ← عوض می‌کرد
 *     WalletTransaction::where(...)->delete()        ← حذف می‌کرد
 *
 * پس مسیرِ کوئری هم با `ImmutableBuilder` بسته شد.
 *
 * ⚠️ `DB::table(...)->delete()` همچنان دورش می‌زند — و همین عمدی است:
 * بازیابیِ بکاپ و هرسِ دوره‌ای باید بتوانند کار کنند.
 */
trait Immutable
{
    /** آیا حذفِ این رکورد هم ممنوع است، یا فقط ویرایش؟ */
    protected static function immutableBlocksDeletion(): bool
    {
        return true;
    }

    /** مسیرِ کوئری هم باید بسته باشد، نه فقط مسیرِ نمونهٔ مدل. */
    public function newEloquentBuilder($query): ImmutableBuilder
    {
        return new ImmutableBuilder($query);
    }

    protected static function bootImmutable(): void
    {
        static::updating(function (Model $model): void {
            throw DomainException::invalid(
                'رکوردِ دفترِ مالی قابلِ ویرایش نیست. برای اصلاح، ردیفِ معکوس ثبت کنید.',
                'ledger.immutable',
            );
        });

        static::deleting(function (Model $model): void {
            if (! static::immutableBlocksDeletion()) {
                return;
            }

            throw DomainException::invalid(
                'رکوردِ دفترِ مالی قابلِ حذف نیست. برای اصلاح، ردیفِ معکوس ثبت کنید.',
                'ledger.immutable',
            );
        });
    }
}
