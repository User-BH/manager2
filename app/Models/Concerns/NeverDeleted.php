<?php

namespace App\Models\Concerns;

use App\Exceptions\DomainException;
use Illuminate\Database\Eloquent\Model;

/**
 * رکوردی که ویرایش می‌شود ولی هرگز حذف نمی‌شود (R51).
 *
 * ─── تفاوتش با `Immutable` ─────────────────────────────────────────────────
 * قبض و پرداخت **باید** قابلِ ویرایش باشند: وضعیتِ قبض از «پرداخت‌نشده» به
 * «تسویه» می‌رود، و پرداخت از «در انتظار» به «موفق». آنچه نباید ممکن باشد،
 * **ناپدیدشدنشان** است.
 *
 * ─── چرا حذف را کاملاً می‌بندیم به‌جای Soft Delete ───────────────────────────
 * ⚠️ برای قبض و پرداخت هیچ عملیاتِ کاربریِ مشروعی به‌نامِ «حذف» وجود ندارد.
 * قبضِ اشتباه با تغییرِ مبلغ اصلاح می‌شود و رسیدِ نادرست با وضعیتِ
 * «ردشده» — نه با پاک‌شدن.
 *
 * Soft Delete اینجا ضعیف‌تر است چون `forceDelete()` را باز می‌گذارد و
 * پرسشِ «آیا این ردیف هست یا نیست» را به هر کوئری تحمیل می‌کند. بستنِ
 * کامل، هم صریح‌تر است هم ساده‌تر.
 *
 * ⚠️ مثلِ `Immutable`، این فقط سدِ Eloquent است. بازیابیِ بکاپ که با
 * `DB::table(...)->delete()` جدول‌ها را خالی می‌کند، عمداً از کنارش رد
 * می‌شود.
 */
trait NeverDeleted
{
    protected static function bootNeverDeleted(): void
    {
        static::deleting(function (Model $model): void {
            throw DomainException::invalid(
                'این رکوردِ مالی قابلِ حذف نیست؛ وضعیتش را تغییر دهید.',
                'finance.not_deletable',
            );
        });
    }
}
