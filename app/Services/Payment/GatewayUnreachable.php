<?php

namespace App\Services\Payment;

use RuntimeException;

/**
 * «نتیجه‌ی این تراکنش را **نمی‌دانم**» (R59).
 *
 * ─── 🔴 شکافی که این کلاس برای بستنش ساخته شد ──────────────────────────────
 * قراردادِ درگاه `verify(): ?string` بود و `null` **دو معنای کاملاً متفاوت**
 * داشت:
 *
 *   ① بانک صریح گفت «این تراکنش ناموفق بود»
 *   ② اصلاً به بانک نرسیدیم — timeout، قطعیِ شبکه، خطای ۵۰۳
 *
 * و `GatewayController::callback` هر دو را یکسان می‌دید: پرداخت را برای
 * همیشه `Failed` علامت می‌زد و به کاربر می‌گفت «پرداخت انجام نشد. اگر مبلغی
 * کسر شده طی ۷۲ ساعت برمی‌گردد».
 *
 * ⚠️ در حالتِ ② این جمله **ممکن است دروغ باشد**. ما نمی‌دانیم پول کسر شده
 * یا نه؛ داریم درباره‌ی چیزی که نمی‌دانیم به کاربر تضمین می‌دهیم.
 *
 * ─── چرا استثنا و نه یک مقدارِ سومِ برگشتی ───────────────────────────────────
 * مقدارِ سوم را می‌شود بی‌سروصدا نادیده گرفت؛ استثنا را نه. هر مصرف‌کننده‌ی
 * تازه‌ای که این حالت را در نظر نگیرد، **می‌ترکد** — و شکستِ بلند در مسیرِ
 * مالی همیشه بهتر از تصمیمِ خاموشِ اشتباه است.
 *
 * ─── قاعده‌ی رفتاری ─────────────────────────────────────────────────────────
 * وقتی این استثنا پرتاب شود، پرداخت **در وضعیتِ `pending` می‌ماند**:
 *
 *   - `Failed` نمی‌شود، چون شاید پول واقعاً کسر شده باشد
 *   - `Success` نمی‌شود، چون شاید نشده باشد
 *
 * و `payments:stale` همین ردیف‌ها را به اپراتور نشان می‌دهد تا در پنلِ بانک
 * تعیینِ تکلیف شوند.
 */
class GatewayUnreachable extends RuntimeException
{
    /**
     * @param  string  $stage  کدام گام — برای اینکه اپراتور بداند دنبالِ چه بگردد
     */
    public function __construct(
        string $message,
        public readonly string $gateway = '',
        public readonly string $stage = '',
    ) {
        parent::__construct($message);
    }

    /**
     * تراکنش نزدِ بانک **تأیید شد** ولی تسویه‌اش قطعی نیست.
     *
     * 🔴 خطرناک‌ترین حالتِ ممکن، و دقیقاً همانی که پیش از R59 بی‌صدا
     * «موفق» گزارش می‌شد: قبض تسویه می‌شد، کیفِ پول شارژ می‌شد، و پولی
     * که هرگز به حسابِ مجتمع ننشسته بود، در دفترها نشسته بود.
     */
    public static function settleUnconfirmed(string $gateway, string $detail): self
    {
        return new self(
            'تراکنش نزدِ بانک تأیید شد ولی تسویه‌اش قطعی نشد ('.$detail.'). '
            .'وضعیتِ این پرداخت باید در پنلِ بانک بررسی شود.',
            $gateway,
            'settle',
        );
    }

    /**
     * بانک تراکنشی را تأیید کرد که با این سفارش نمی‌خواند — یا نمی‌شود فهمید
     * که می‌خواند (مرحلهٔ ۵ · فاز ۹).
     *
     * 🔴 «ناموفق» نیست: بانک «بله» گفته و پولی روی ترمینالِ ما جابه‌جا شده.
     * «موفق» هم نیست: شاید تراکنشِ ارزانِ دیگری است که به این سفارش چسبانده
     * شده. تنها پاسخِ درست بررسیِ دستی است.
     */
    public static function unmatched(string $gateway, string $detail): self
    {
        return new self(
            'بانک تراکنشی را تأیید کرد که با این سفارش نمی‌خواند ('.$detail.'). '
            .'این پرداخت تسویه نشد و باید در پنلِ بانک بررسی شود.',
            $gateway,
            'match',
        );
    }

    public static function transport(string $gateway, string $stage, string $detail): self
    {
        return new self(
            'ارتباط با درگاه در گامِ «'.$stage.'» برقرار نشد ('.$detail.').',
            $gateway,
            $stage,
        );
    }
}
