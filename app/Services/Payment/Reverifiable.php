<?php

namespace App\Services\Payment;

/**
 * درگاهی که نتیجه‌ی یک پرداخت را **بی بازگشتِ مرورگر** می‌تواند دوباره بپرسد (مرحلهٔ ۱۲ · فاز ۲).
 *
 * برای بازبینیِ دوره‌ای (`payments:reconcile`): پرداختی که بازگشتش نرسید یا درگاه آن لحظه پاسخ نداد. قرارداد:
 *
 * - رشته: پرداخت انجام و همین حالا تأیید شد — کدِ رهگیری؛
 * - `null`: درگاه قطعاً می‌گوید پرداختی انجام نشده (لغو، انقضا، برگشتِ خودکارِ بانک)؛
 * - `GatewayUnreachable`: هنوز نامعلوم — هیچ چیز عوض نمی‌شود.
 *
 * ملت و سامان این را ندارند: تأییدشان داده‌ای از بازگشتِ بانک می‌خواهد (`RefNum`، `SaleReferenceId`) که وقتی بازگشت
 * نرسیده نداریم؛ پرداختِ نامعلومِ آن‌ها فقط در `payments:stale` گزارش می‌شود.
 */
interface Reverifiable
{
    public function reverify(GatewayOrder $order): ?string;
}
