<?php

namespace App\Services\Health;

/**
 * خواندنِ فضای دیسک — تنها جایی که به فایل‌سیستمِ واقعی دست می‌زند.
 *
 * ─── 🔴 چرا این کلاس از `HealthReport` جدا شد (مرحلهٔ ۵، فاز ۱) ─────────────
 * پیش از این، `HealthReport::disk()` مستقیم `disk_free_space()` را صدا
 * می‌زد. نتیجه‌اش این بود که **نتیجهٔ تست به حالتِ ماشین بستگی داشت**:
 *
 *   دیسکِ ۹۸٪ → پنج تستِ سلامت قرمز
 *   دیسکِ ۹۳٪ → همان پنج تست سبز، **بدونِ یک خط تغییرِ کد**
 *
 * ⚠️ این در ممیزیِ تجمیعی به‌عنوانِ `S4-27` ثبت شد و با آزمایش هم اثبات
 * شد. تستی که با پرشدنِ دیسکِ توسعه‌دهنده قرمز شود، تستِ آن رفتار نیست.
 *
 * ─── و چرا «فقط در تست جعلش کنیم» کافی نبود ────────────────────────────────
 * 🔴 نگاشتِ شدتِ دیسک (۸۵٪ → `degraded`، ۹۷٪ → `down`) **هیچ تستِ
 * مستقیمی نداشت**. تنها راهی که اثرش دیده می‌شد، پر شدنِ دیسکِ واقعیِ کسی
 * بود.
 *
 * پس این جداسازی پوشش را **زیاد** می‌کند نه کم: مسیرِ سنجش قابلِ تثبیت
 * می‌شود و خودِ نگاشت `DiskThresholdTest` را می‌گیرد.
 */
class DiskSpace
{
    /**
     * فضای کل و آزادِ مسیرِ داده‌شده، بر حسبِ بایت.
     *
     * ⚠️ `null` یعنی «این محیط جواب نمی‌دهد» — نه «دیسک پر است». تفاوتشان
     * مهم است: اولی نباید هشدار بسازد.
     *
     * @return array{total: float, free: float}|null
     */
    public function usage(string $path): ?array
    {
        $total = @disk_total_space($path);
        $free = @disk_free_space($path);

        if ($total === false || $free === false || $total <= 0.0) {
            return null;
        }

        return ['total' => (float) $total, 'free' => (float) $free];
    }
}
