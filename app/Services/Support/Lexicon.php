<?php

namespace App\Services\Support;

use App\Support\PersianText;

/**
 * واژه‌نامه‌ی دستیار: مترادف‌ها و مرزِ دامنه.
 *
 * ─── چرا جدا از `KnowledgeBase` ────────────────────────────────────────────
 * `KnowledgeBase` می‌گوید هر موضوع **چه پاسخی** دارد. اینجا می‌گوید کاربر
 * ممکن است همان مفهوم را **با چه واژه‌ی دیگری** بگوید. اگر مترادف‌ها را داخل
 * کلیدواژه‌های هر موضوع می‌ریختیم، «صورتحساب» باید هم در `charge` می‌آمد هم
 * در `payment` هم در `export` — و هر بار که یکی را عوض می‌کردیم، بقیه از
 * قلم می‌افتادند.
 */
class Lexicon
{
    /**
     * مترادف → واژه‌ی متعارف.
     *
     * ─── دو شرطی که هر سطر باید داشته باشد ─────────────────────────────────
     * ① سمتِ راست باید **دقیقاً** کلیدواژه‌ی موجودِ `KnowledgeBase` باشد،
     *    وگرنه سطر بی‌صدا بی‌اثر است.
     * ② سمتِ چپ نباید خودش از قبل به کلیدواژه‌ای بخورد، وگرنه یک مفهوم
     *    **دوبار** امتیاز می‌گیرد.
     *
     * ⚠️ این فهرست را اول از روی شهود نوشتم: از ۴۶ سطر، ۲۴ سطر شرطِ ② را
     * می‌شکستند و ۶ سطر شرطِ ① را. یکی از همان‌ها («رمزعبور» → «پسورد»)
     * پرسشِ «رمز عبور چطور نگهداری می‌شود» را از موضوعِ **امنیت** به
     * **ثبت‌نام** برد، چون هم «رمز» امتیاز می‌گرفت هم مترادفش «پسورد».
     * علتِ ریشه‌ای این بود که `KnowledgeBase` از R32 به‌قدرِ کافی پر است؛
     * لایه‌ی مترادف فقط جایی می‌ارزد که واژه‌ای **بیرونِ** آن باشد. تستِ
     * ساختاری هر دو شرط را نگه می‌دارد.
     *
     * @var array<string,string>
     */
    private const SYNONYMS = [
        // ثبت‌نام و ورود — واژه‌های فرنگی که کاربر جوان‌تر می‌نویسد
        'رجیستر' => 'ثبتنام',
        'اکانت' => 'حساب',
        'یوزر' => 'حساب',
        'گذرواژه' => 'پسورد',
        'همراه' => 'موبایل',

        // شارژ و قبض — واژه‌ی اداری در برابر واژه‌ی روزمره
        'صورتحساب' => 'قبض',
        'صورتوضعیت' => 'قبض',
        'حقشارژ' => 'شارژ',
        'شارژماهانه' => 'شارژ',
        'مساحت' => 'متراژ',
        'لیفت' => 'اسانسور',

        // پرداخت
        'تسویه' => 'پرداخت',
        'رسیدواریز' => 'رسید',

        // امنیت و بکاپ
        'محفوظ' => 'امنیت',
        'ریستور' => 'بازیابی',

        // نظرسنجی
        'رایدادن' => 'نظرسنجی',
        'همهپرسی' => 'نظرسنجی',

        // هزینه
        'نرخ' => 'تعرفه',
    ];

    /**
     * واژه‌هایی که قاطعانه بیرون از دامنه‌ی این سامانه‌اند.
     *
     * ─── چرا لازم شد ───────────────────────────────────────────────────────
     * «قیمت دلار چند شد» با اطمینان به موضوعِ **هزینه‌ها** می‌رفت، چون
     * «قیمت» واقعاً کلیدواژه‌ی آن موضوع است. هیچ آستانه‌ای این را نمی‌گرفت:
     * از دیدِ امتیاز، این پرسش یک پرسشِ درست‌وحسابی درباره‌ی قیمت است.
     * تنها چیزی که فرقش را می‌گوید خودِ واژه‌ی «دلار» است.
     *
     * پس این فهرست **وتو** می‌کند، نه امتیازدهی: اگر چنین واژه‌ای در پیام
     * باشد، پاسخِ پیش‌فرض داده می‌شود حتی اگر امتیاز بالا باشد.
     *
     * @var array<int,string>
     */
    private const OUT_OF_DOMAIN = [
        // بازار و ارز — پرتکرارترین پرسشِ پرت با واژه‌ی مشترک («قیمت»)
        'دلار', 'یورو', 'طلا', 'سکه', 'بورس', 'ارز', 'بیتکوین', 'رمزارز', 'مسکن',
        // سرگرمی
        'فوتبال', 'والیبال', 'بازیکن', 'استقلال', 'پرسپولیس', 'فیلم', 'سریال',
        'اهنگ', 'موزیک', 'شعر', 'جوک', 'لطیفه', 'قرعهکشی',
        // زندگیِ روزمره‌ی بی‌ربط
        'هواشناسی', 'ابوهوا', 'اشپزی', 'رستوران', 'سفر', 'بلیط', 'پرواز',
        'داروخانه', 'پزشک', 'کنکور', 'دانشگاه',
    ];

    /**
     * دشنام و توهین.
     *
     * ⚠️ این فهرست **جای پاسخ را عوض نمی‌کند**، فقط جلوی «اطمینان» را
     * می‌گیرد وقتی پیام هیچ پرسشِ واقعی ندارد. اگر کاربر عصبانی باشد ولی
     * پرسشِ درستی هم بپرسد («قبض شارژتون مزخرفه، چطور اصلاحش کنم؟»)،
     * پاسخِ موضوع را می‌گیرد — عصبانیت دلیلِ بی‌پاسخ‌گذاشتن نیست.
     *
     * @var array<int,string>
     */
    private const PROFANITY = [
        'احمق', 'بیشعور', 'خر', 'کصافت', 'کثافت', 'اشغال', 'عوضی', 'لعنت',
        'مزخرف', 'مسخره', 'چرت', 'بیخود', 'گوه', 'کوفت', 'درد',
    ];

    /**
     * واژه‌های پیام + شکلِ متعارفِ مترادف‌ها.
     *
     * @return array<int,string>
     */
    public static function expand(string $message): array
    {
        $terms = PersianText::searchTerms($message);

        foreach ($terms as $term) {
            if (isset(self::SYNONYMS[$term])) {
                $terms[] = self::SYNONYMS[$term];
            }
        }

        return array_values(array_unique($terms));
    }

    /**
     * آیا پیام نشانه‌ی صریحِ «بیرون از دامنه» دارد؟
     *
     * تطبیق **دقیق** است نه پیشوندی: «هوا» نباید «هواکش» را وتو کند، که
     * خودش یک درخواستِ تعمیراتِ واقعی است.
     */
    public static function isOutOfDomain(string $message): bool
    {
        $tokens = PersianText::tokens($message);

        return array_intersect($tokens, self::OUT_OF_DOMAIN) !== [];
    }

    public static function hasProfanity(string $message): bool
    {
        $tokens = PersianText::tokens($message);

        foreach ($tokens as $token) {
            foreach (self::PROFANITY as $word) {
                // پیشوندی، چون «مزخرفه» و «مسخرست» شکل‌های همان واژه‌اند
                if (str_starts_with($token, $word)) {
                    return true;
                }
            }
        }

        return false;
    }

    /**
     * برای تست: هر مترادف باید به کلیدواژه‌ی موجود اشاره کند.
     *
     * @return array<string,string>
     */
    public static function synonyms(): array
    {
        return self::SYNONYMS;
    }
}
