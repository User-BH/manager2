    /**
     * موضوع‌هایی که همین حالا در دسترس‌اند، با پاسخِ متناسب با قابلیت‌های روشن.
     *
     * @return array<int,array<string,mixed>>
     */
    public static function available(): array
    {
        $flags = app(FeatureFlags::class);
        $intents = [];

        foreach (self::intents() as $intent) {
            if (isset($intent['feature']) && ! $flags->enabled($intent['feature'])) {
                continue;
            }

            foreach ($intent['whenOff'] ?? [] as $flag => $override) {
                if (! $flags->enabled($flag)) {
                    $intent = array_merge($intent, $override);
                }
            }

            unset($intent['whenOff']);
            $intents[] = $intent;
        }

        return $intents;
    }

    /**
     * چهار پرسشِ پیشنهادی، فقط از موضوع‌های در دسترس.
     *
     * @return array<int,string>
     */
    public static function starters(): array
    {
        $available = array_column(self::available(), 'id');

        return array_slice(array_keys(array_filter(
            self::starterIntents(),
            fn (string $intent) => in_array($intent, $available, true),
        )), 0, 4);
    }

