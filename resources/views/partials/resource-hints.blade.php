    ⚠️ باید **پیش از** تگ‌های `@vite` بیاید. مرورگر head را به‌ترتیب می‌خواند
    و اگر preload بعد از CSS بیاید، دیگر چیزی را جلو نینداخته است.
--}}

{{--
    فونتِ متنِ اصلی.

    ─── چرا فقط همین یکی ──────────────────────────────────────────────────
    فونت در CSS اعلام شده، یعنی مرورگر تا CSS را دانلود و تجزیه نکند اصلاً
    نمی‌داند چنین فایلی لازم است — یک رفت‌وبرگشتِ کامل روی مسیرِ بحرانی.
    `preload` این کشف را به همان اولین بایتِ HTML جلو می‌آورد.

    ⚠️ ولی preloadِ **هر چهار وزن** ضدِ خودش عمل می‌کند: ‎۲۰۰KB فونت با
    اولویتِ بالا با خودِ CSS و JS بر سر پهنای باند رقابت می‌کند، در حالی که
    متنِ بدنه فقط به Regular نیاز دارد و بقیه با `font-display: swap` بی‌سر
    و صدا بعداً می‌رسند.

    `crossorigin` اجباری است حتی برای فایلِ هم‌مبدأ: بدونش مرورگر فایل را
    **دو بار** می‌گیرد، چون درخواستِ preload و درخواستِ واقعیِ فونت دو حالتِ
    CORS متفاوت دارند و کشِ یکی به کارِ دیگری نمی‌آید.
--}}
<link rel="preload" as="font" type="font/woff2" crossorigin href="{{ Vite::asset('resources/fonts/Vazirmatn-Regular.woff2') }}">

@isset($lcpImage)
    {{--
        تصویرِ بزرگِ بالای صفحه (LCP).

        این تصویر را React رندر می‌کند، یعنی مرورگر تا JS اجرا نشود آدرسش را
        نمی‌بیند. برای صفحه‌ی فرود — که سرعتش برای SEO مهم است — این یعنی
        بزرگ‌ترین عنصرِ صفحه دیرترین چیزی است که شروع به آمدن می‌کند.
    --}}
    <link rel="preload" as="image" href="{{ $lcpImage }}" fetchpriority="high">
@endisset

{{--
    اتصالِ زودهنگام به مبدأهای بیرونی.

    ⚠️ فقط مبدأهایی که **واقعاً** تنظیم شده‌اند. `preconnect` به دامنه‌ای که
    هیچ درخواستی به آن نمی‌رود، یک اتصالِ TLSِ بی‌مصرف باز می‌کند و سهمیه‌ی
    اتصال‌های هم‌زمان را از منابعِ واقعی می‌گیرد — یعنی صفحه را **کندتر**
    می‌کند.
--}}
@foreach (\App\Support\ResourceHints::origins() as $origin)
    <link rel="preconnect" href="{{ $origin }}" crossorigin>
    <link rel="dns-prefetch" href="{{ $origin }}">
@endforeach
