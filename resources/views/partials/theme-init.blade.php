{{--
    تمِ صفحه، پیش از اولین رنگ‌آمیزی (مرحلهٔ ۷ · فاز ۱).

    ─── قاعده ────────────────────────────────────────────────────────────────
    پیش‌فرض **روشن** است. تیره فقط وقتی که خودِ کاربر با دکمه‌ی تم انتخابش
    کرده باشد. تمِ سیستم‌عامل عمداً خوانده نمی‌شود.

    ─── 🔴 چه چیزی خراب بود ─────────────────────────────────────────────────
    ① هر پوسته نسخه‌ی خودش از این اسکریپت را داشت (داشبورد، صفحه‌های عمومی،
       انتقال به درگاه) و هر سه بی‌انتخابِ کاربر تمِ سیستم‌عامل را می‌گرفتند.
    ② `themeStore` همان حدس را در اولین بازدید **ذخیره** می‌کرد؛ یعنی
       «انتخابی» ثبت می‌شد که کاربر هرگز نکرده بود و از آن به بعد پاک
       نمی‌شد.

    ⚠️ کلیدِ ذخیره عوض شد (`theme` ← `sakena:theme`): مقدارهای کلیدِ قدیم با
    حدسِ خودکار آلوده‌اند و از انتخابِ واقعی جدا نمی‌شوند. همان کلید را
    `themeStore.ts` هم می‌خواند و می‌نویسد.

    رنگِ نوارِ مرورگر (`theme-color`) هم از همین‌جا با تم یکی می‌شود؛ پیش از
    این با `media` از سیستم‌عامل پیروی می‌کرد و روی صفحه‌ی روشن، نوارِ تیره
    می‌گذاشت.
--}}
<script @csp>
    (function () {
        var dark = false;
        try {
            dark = localStorage.getItem('sakena:theme') === 'dark';
        } catch (e) {}
        document.documentElement.classList.toggle('dark', dark);
        var bar = document.querySelector('meta[name="theme-color"]');
        if (bar) bar.setAttribute('content', dark ? '#0f1411' : '#0f6e56');
    })();
</script>
