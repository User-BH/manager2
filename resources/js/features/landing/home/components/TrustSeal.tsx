import { useEffect, useRef } from 'react'

/** همان شناسه‌ای که `views/public/home.blade.php` روی گره‌ی نشان می‌گذارد. */
const SEAL_ID = 'enamad-seal'

/**
 * نشانِ اعتمادِ الکترونیکی (اینماد) در فوتر.
 *
 * ─── چرا این کامپوننت خودش نشان را نمی‌سازد ────────────────────────────────
 * بررسیِ خودکارِ اینماد صفحه را **بدونِ اجرای جاوااسکریپت** می‌خواند. صفحه‌ی
 * فرودِ ما یک island است و کلِ فوتر سمتِ کلاینت رندر می‌شود، پس نشانی که
 * اینجا ساخته شود در HTMLِ خامِ سرور وجود ندارد و در آن بررسی دیده نمی‌شود
 * — یعنی تاییدیه نمی‌گیرد. (با `curl` روی خروجیِ واقعی سنجیده شد.)
 *
 * پس نشان در Blade رندر می‌شود و این کامپوننت فقط **همان گره را جابه‌جا
 * می‌کند** تا سرِ جای درستش در فوتر بنشیند.
 *
 * ─── چرا گره در Blade پنهان است ────────────────────────────────────────────
 * تا پیش از mountِ React، `#root` خالی است. در نسخه‌ی اول این گره پنهان
 * نبود، پس **تنها چیزِ قابلِ دیدنِ صفحه** می‌شد: نشان وسطِ صفحه‌ی سفید بالا
 * می‌آمد و با آمدنِ بقیه‌ی صفحه به فوتر می‌پرید. حالا با `display:none`
 * شروع می‌شود و همین‌جا — پس از رسیدن به جای درستش — نمایان می‌شود.
 */
export function TrustSeal() {
  const slotRef = useRef<HTMLDivElement>(null)

  useEffect(() => {
    const seal = document.getElementById(SEAL_ID)
    const slot = slotRef.current

    if (!seal || !slot) return

    if (!slot.contains(seal)) {
      slot.appendChild(seal)
    }

    // اول جابه‌جا، بعد نمایان — ترتیبش مهم است، وگرنه یک فریم بالا دیده می‌شود
    seal.style.display = ''

    /*
     * با unmount گره به بدنه برمی‌گردد و پاک نمی‌شود: اگر حذفش می‌کردیم،
     * پیمایشِ درون‌برنامه‌ای می‌توانست نشان را برای همیشه از صفحه بردارد.
     * دوباره پنهان می‌شود تا در فاصله‌ی بی‌صاحبی وسطِ صفحه ظاهر نشود.
     */
    return () => {
      if (seal.parentElement === slot) {
        seal.style.display = 'none'
        document.body.appendChild(seal)
      }
    }
  }, [])

  return <div ref={slotRef} className="shrink-0" />
}
