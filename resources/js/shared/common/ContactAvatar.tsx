/**
 * آواتارِ تصویریِ سبکِ «مخاطبینِ موبایل» (R33).
 *
 * ─── چرا عکسِ واقعی برداشته شد ─────────────────────────────────────────────
 * سه عکسِ استوکِ آدم‌های واقعی کنارِ نقلِ‌قول‌هایی نشسته بودند که آن آدم‌ها
 * نگفته‌اند. حتی با نیتِ خوب، این یعنی چهره‌ی یک انسانِ واقعی زیرِ حرفی
 * برود که نزده — و بازدیدکننده هم اگر عکس را جای دیگری ببیند، اعتمادش به
 * کلِ صفحه می‌ریزد.
 *
 * ─── چرا SVGِ درون‌خطی و نه فایل ───────────────────────────────────────────
 * سه فایلِ تصویر یعنی سه درخواستِ شبکه برای چیزی که چند صد بایت مسیرِ
 * برداری است. اینجا هیچ فایلی، هیچ پکیجی، و هیچ درخواستی اضافه نمی‌شود؛
 * رنگ‌ها هم از متغیرهای تم می‌آیند، پس در تمِ تیره هم درست دیده می‌شود.
 *
 * ─── چرا رنگ از نام مشتق می‌شود ───────────────────────────────────────────
 * با رنگِ ثابت، سه آواتار عینِ هم می‌شدند و کارت‌ها از هم تفکیک نمی‌شدند.
 * مشتق‌کردن از نام یعنی هر شخص رنگِ پایدارِ خودش را دارد، بدونِ اینکه لازم
 * باشد رنگ را دستی در داده بنویسیم.
 */

/** پالتِ آواتار — هم‌خانواده‌ی برند، با کنتراستِ کافی روی سفیدِ چهره. */
const PALETTE = ['#0f6e56', '#2563eb', '#b45309', '#7c3aed', '#be123c', '#0f766e']

/** هشِ پایدارِ نام → اندیسِ رنگ. الگوریتم مهم نیست، پایدار بودنش مهم است. */
function paletteFor(seed: string): string {
  let sum = 0

  for (let i = 0; i < seed.length; i++) {
    sum = (sum + seed.charCodeAt(i) * (i + 1)) % 997
  }

  return PALETTE[sum % PALETTE.length]
}

export function ContactAvatar({
  name,
  size = 44,
  className,
}: {
  name: string
  size?: number
  className?: string
}) {
  const color = paletteFor(name)

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 64 64"
      className={className}
      role="img"
      aria-label={name}
    >
      {/* پس‌زمینه‌ی دایره‌ای، کم‌رنگ‌شده تا چهره رویش دیده شود */}
      <circle cx="32" cy="32" r="32" fill={color} opacity="0.16" />

      {/*
        سر و شانه — همان شمایلی که کاربر در دفترچه‌ی مخاطبینِ گوشی‌اش
        می‌بیند. شانه با `clipPath` بریده می‌شود تا از دایره بیرون نزند.
      */}
      <clipPath id={`avatar-clip-${size}-${color.slice(1)}`}>
        <circle cx="32" cy="32" r="32" />
      </clipPath>

      <g clipPath={`url(#avatar-clip-${size}-${color.slice(1)})`} fill={color}>
        <circle cx="32" cy="25" r="11" />
        <path d="M32 39c-10.5 0-19 6.6-19 14.8V64h38V53.8C51 45.6 42.5 39 32 39z" />
      </g>
    </svg>
  )
}
