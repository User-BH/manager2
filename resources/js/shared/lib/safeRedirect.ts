/**
 * مسیرِ بازگشتِ داخلی — یا `null` اگر قابل اعتماد نباشد.
 *
 * ─── چرا لازم است ──────────────────────────────────────────────────────────
 * بعد از ورود، کاربر باید به همان صفحه‌ای برگردد که می‌خواست. طبیعی‌ترین
 * پیاده‌سازی این است که مسیرِ ذخیره‌شده مستقیم به `location.replace` داده شود —
 * و همان‌جاست که «هدایتِ باز» (open redirect) ساخته می‌شود.
 *
 * نکته‌ای که راحت از قلم می‌افتد: `//evil.com` یک **مسیرِ معتبر** است و
 * `pathname` می‌تواند دقیقاً همین باشد. ولی `location.replace('//evil.com')`
 * آدرسِ نسبی‌به‌پروتکل حساب می‌شود و مرورگر را به دامنه‌ی دیگری می‌برد. یعنی
 * شرطِ «با / شروع می‌شود» به‌تنهایی **کافی نیست**.
 *
 * چرا مهم است: صفحه‌ای که کاربر را بلافاصله پس از ورود به سایتِ مهاجم می‌برد،
 * قانع‌کننده‌ترین جای ممکن برای یک صفحه‌ی ورودِ جعلی است.
 *
 * ⚠️ امروز این مسیر عملاً غیرقابلِ دسترس است: صفحه‌ی ورود یک سندِ MPAِ جداست و
 * `ProtectedRoute` با ناوبریِ کاملِ مرورگر به آن می‌رود، پس `location.state`
 * پاک می‌شود و `from` همیشه تهی است. این محافظ برای روزی است که کسی آن مسیر
 * را (همان‌طور که مستنداتِ کامپوننت وعده می‌دهد) واقعاً وصل کند.
 */
export function safeInternalPath(
  from?: { pathname?: string; search?: string } | null,
): string | null {
  const pathname = from?.pathname
  if (!pathname) return null

  // باید مسیرِ مطلقِ داخلی باشد: با یک `/` شروع شود ولی نه `//` و نه `/\`
  if (!pathname.startsWith('/')) return null
  if (pathname.startsWith('//') || pathname.startsWith('/\\')) return null

  const search = from?.search ?? ''
  if (search && !search.startsWith('?')) return null

  return `${pathname}${search}`
}
