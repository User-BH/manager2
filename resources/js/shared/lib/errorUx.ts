import { ApiError } from './apiError'

/**
 * از کدِ وضعیت تا کاری که کاربر باید بکند (R69).
 *
 * ─── 🔴 نقصی که اندازه‌گیری پیدا کرد ────────────────────────────────────────
 * `alertError` فقط ۴۰۲ را جدا می‌دید. ۴۰۱، ۴۰۳، ۴۰۴، ۴۰۹، ۴۲۹ و همه‌ی
 * ۵xx **دقیقاً یک دیالوگِ قرمز** می‌گرفتند با متنِ سرور و هیچ راهنمایی.
 *
 * ⚠️ نتیجه‌اش این بود که کاربر می‌فهمید «نشد»، ولی نمی‌فهمید چه کند:
 *
 *   ۴۰۱ → نشستش تمام شده و باید دوباره وارد شود
 *   ۴۰۹ → کسِ دیگری هم‌زمان تغییرش داده و باید صفحه را تازه کند
 *   ۴۲۹ → باید چند ثانیه صبر کند
 *   ۵۰۳ → باید چند دقیقه بعد برگردد
 *
 * این چهار کارِ کاملاً متفاوت‌اند و یک پیامِ یکسان هیچ‌کدام را نمی‌گوید.
 *
 * ─── ⚠️ چرا عنوان از سرور می‌آید و راهنما از اینجا ──────────────────────────
 * پیامِ سرور معمولاً **دقیق‌تر** است («سهمیه‌ی پیامک این ماه مصرف شده»)، پس
 * جایگزین‌کردنش با متنِ عمومی، اطلاعات را کم می‌کند.
 *
 * ولی سرور نمی‌داند کاربر در کدام صفحه است و چه کاری نیمه‌تمام مانده؛
 * «چه کنم» کارِ لایه‌ی رابط است. پس عنوان از سرور، راهنما از این نگاشت.
 */
export interface ErrorUx {
  /** عنوانِ دیالوگ — پیامِ سرور، وگرنه متنِ جایگزین. */
  title: string

  /** یک جمله: کاربر حالا چه کند. خالی یعنی راهنمای معناداری وجود ندارد. */
  hint: string

  /**
   * ⚠️ آیکون بخشی از پیام است، نه تزئین.
   *
   * «دسترسی ندارید» خطای کاربر نیست و آیکونِ قرمزِ خطا آن را شبیهِ خرابی
   * نشان می‌دهد؛ «سرور پاسخ نداد» واقعاً خطاست.
   */
  icon: 'error' | 'warning' | 'info'
}

/** ⚠️ ثانیه، گردشده به بالا: «۰ ثانیه صبر کنید» راهنمایی نیست. */
function waitSeconds(retryAfterMs: number | undefined): number {
  if (typeof retryAfterMs !== 'number' || !Number.isFinite(retryAfterMs)) return 0

  return Math.max(1, Math.ceil(retryAfterMs / 1000))
}

function hintFor(status: number, retryAfterMs?: number): string {
  if (status === 429) {
    const seconds = waitSeconds(retryAfterMs)

    return seconds > 0
      ? `درخواست‌های زیادی فرستاده شده. حدود ${seconds} ثانیه صبر کنید و دوباره تلاش کنید.`
      : 'درخواست‌های زیادی فرستاده شده. کمی صبر کنید و دوباره تلاش کنید.'
  }

  switch (status) {
    /*
     * ⚠️ صفر یعنی پاسخی نرسید (قطعیِ شبکه یا مهلتِ تمام‌شده) — نه خطای
     * سرور. تفکیکش مهم است: کاربر باید اینترنتش را نگاه کند، نه منتظرِ
     * رفعِ مشکل از سمتِ ما بماند.
     */
    case 0:
      return 'ارتباط با سرور برقرار نشد. اتصالِ اینترنت را بررسی کنید و دوباره بزنید.'

    /*
     * 🔴 عمداً خودکار به صفحه‌ی ورود نمی‌بریم.
     *
     * کاربری که وسطِ پرکردنِ فرمِ هزینه است، با یک ریدایرکتِ ناگهانی همه‌ی
     * کارش را از دست می‌دهد. همان استدلالی که در R61 جلوی بارگذاریِ
     * اجباری را هم گرفت.
     */
    case 401:
      return 'نشستِ شما پایان یافته است. در تبی دیگر وارد شوید و دوباره تلاش کنید.'

    case 403:
      return 'اگر فکر می‌کنید باید به این بخش دسترسی داشته باشید، با مدیرِ مجتمع تماس بگیرید.'

    case 404:
      return 'شاید این مورد حذف شده باشد. فهرست را تازه کنید.'

    /*
     * ⚠️ ۴۰۹ یعنی وضعیت زیرِ دستِ کاربر عوض شده — نه اینکه کارش غلط بوده.
     * تازه‌کردن، تنها راهِ درستِ ادامه است.
     */
    case 409:
      return 'وضعیتِ این مورد در این فاصله تغییر کرده. صفحه را تازه کنید و دوباره تلاش کنید.'

    case 419:
      return 'صفحه را تازه کنید و دوباره تلاش کنید.'

    /*
     * ⚠️ ۴۲۲ عمداً راهنما ندارد: خطاهای فیلد **زیرِ همان فیلد** نشان داده
     * می‌شوند و جمله‌ی عمومی فقط دیالوگ را شلوغ می‌کند.
     */
    case 422:
      return ''

    case 500:
      return 'مشکل از سمتِ ماست. اگر دوباره تکرار شد، کدِ پیگیری را به پشتیبانی بدهید.'

    case 502:
    case 504:
      return 'سرور به‌موقع پاسخ نداد. چند لحظه بعد دوباره تلاش کنید.'

    case 503:
      return 'سامانه موقتاً در دسترس نیست (احتمالاً به‌روزرسانی). چند دقیقه بعد دوباره سر بزنید.'

    default:
      return ''
  }
}

function iconFor(status: number): ErrorUx['icon'] {
  // ⚠️ ۴۰۱ و ۴۱۹ خرابی نیستند؛ نشست تمام شده و این وضعیتِ عادیِ زمان است
  if (status === 401 || status === 419) return 'info'

  if (status === 0 || status === 403 || status === 404 || status === 409 || status === 429) {
    return 'warning'
  }

  if (status === 503) return 'warning'

  return 'error'
}

/**
 * ⚠️ ورودی `unknown` است چون همه‌ی صداکننده‌ها `catch (error)` دارند و
 * تایپِ واقعی‌اش در زمانِ اجرا معلوم می‌شود.
 */
export function errorUx(error: unknown, fallback: string): ErrorUx {
  if (!(error instanceof ApiError)) {
    return {
      title: error instanceof Error && error.message ? error.message : fallback,
      hint: '',
      icon: 'error',
    }
  }

  return {
    title: error.message || fallback,
    hint: hintFor(error.status, error.retryAfterMs),
    icon: iconFor(error.status),
  }
}
