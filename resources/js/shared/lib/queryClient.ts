import { QueryClient, hashKey, type QueryKey } from '@tanstack/react-query'
import { useAuthStore } from '@/shared/stores/authStore'

/**
 * کلیدِ کش با زمینه‌ی فعال (مرحلهٔ ۱۰ · فاز ۴؛ بندِ ۸۳ ِ فایلِ معماری).
 *
 * یک حساب در چند مجتمع عضو است و همان نشانی (`/units`، `/my-bills`) در هر مجتمع دادهٔ
 * دیگری می‌دهد. هر کلید با «حساب و مجتمعِ فعال» درهم‌سازی می‌شود، پس کشِ مجتمعِ الف
 * هرگز در زمینه‌ی ب پاسخ داده نمی‌شود — حتی اگر جایی بی ناوبریِ کامل زمینه عوض شود
 * (`enterNewContext` همیشه با ناوبریِ کامل می‌رود؛ این لایه‌ی دوم است). کلیدهای
 * `queryKeys` دست نمی‌خورند و ابطال (`invalidateQueries`) مثلِ قبل با پیشوند کار می‌کند.
 */
export function contextualHash(queryKey: QueryKey): string {
  const user = useAuthStore.getState().user
  return hashKey([user?.id ?? 0, user?.complex?.id ?? 0, ...queryKey])
}

/**
 * پیکربندیِ TanStack Query.
 *
 * ─── چرا `retry: false`؟ (مهم‌ترین تصمیمِ این فایل) ─────────────────────────
 *
 * پیش‌فرضِ TanStack Query سه تلاش روی **هر** خطاست. اگر همان را می‌گذاشتیم،
 * روی لایه‌ی حمل‌ونقلِ R5 که خودش تا سه بار تلاش می‌کند سوار می‌شد و نتیجه
 * **۳ × ۳ = ۹ درخواست** برای یک خطای ساده بود — دقیقاً همان چیزی که قرار بود
 * جلویش را بگیریم.
 *
 * پس مرزها روشن است:
 *   • تلاشِ دوباره مالِ لایه‌ی حمل‌ونقل است (`shared/lib/retry.ts`)، چون آنجا
 *     همه‌ی مصرف‌کننده‌ها — از جمله جزیره‌های MPA و mutationها — از آن بهره
 *     می‌برند، و `isRetryable` تنها مرجعِ تصمیم است.
 *   • TanStack Query مالکِ **کش، ابطال و همگام‌سازی** است، نه شبکه.
 *
 * یعنی سیاستِ retry همچنان یک منبع دارد؛ اینجا صرفاً به آن منبع واگذار می‌شود.
 *
 * ─── چرا `refetchOnWindowFocus: false`؟ ────────────────────────────────────
 * پیش‌فرضش روشن است. در پنلی که مدیرِ ساختمان چند تب باز نگه می‌دارد، هر بار
 * برگشتن به تب یک رگبارِ درخواست می‌شد. با `staleTime` سی‌ثانیه‌ای، داده‌ی
 * تازه‌ی کمتر از نیم دقیقه دوباره گرفته نمی‌شود. صفحه‌هایی که واقعاً زنده‌اند
 * (اعلان، مسنجر) خودشان این را در سطحِ همان query روشن می‌کنند.
 */
export function createQueryClient(): QueryClient {
  return new QueryClient({
    defaultOptions: {
      queries: {
        // شبکه و تلاشِ دوباره کارِ لایه‌ی زیرین است — بالا را ببینید
        retry: false,

        queryKeyHashFn: contextualHash,

        /*
         * داده تا نیم دقیقه «تازه» است. عددِ کوچک یعنی درخواستِ زیاد، عددِ
         * بزرگ یعنی کاربر داده‌ی کهنه می‌بیند. برای داده‌های مالیِ این پنل که
         * ثانیه‌ای عوض نمی‌شوند، نیم دقیقه تعادلِ معقولی است.
         */
        staleTime: 30_000,

        /** داده‌ی بی‌مصرف پنج دقیقه در حافظه می‌ماند تا برگشتِ کاربر آنی باشد. */
        gcTime: 5 * 60_000,

        refetchOnWindowFocus: false,
        /** برگشتِ اینترنت اما ارزشِ تازه‌کردن دارد. */
        refetchOnReconnect: true,
      },
      mutations: {
        /*
         * mutation هرگز خودکار تکرار نمی‌شود. یک `POST /payments` که timeout
         * شده ممکن است روی سرور انجام شده باشد؛ تکرارش پرداختِ دوم می‌سازد.
         * (لایه‌ی حمل‌ونقل هم به همین دلیل POST را تکرار نمی‌کند.)
         */
        retry: false,
      },
    },
  })
}
