import { useEffect } from 'react'

/**
 * هشدار پیش از بستنِ صفحه وقتی تغییرِ ذخیره‌نشده هست (بند ۲۵).
 *
 * ─── 🔴 چه چیزی نبود ───────────────────────────────────────────────────────
 * هیچ‌جای پروژه `beforeunload` یا معادلش نداشت. یعنی کاربری که پنج دقیقه
 * تنظیماتِ مجتمع را پر کرده بود، با یک بستنِ تبِ اشتباهی همه‌اش را از دست
 * می‌داد — بی‌هیچ پرسشی.
 *
 * ─── ⚠️ مرزِ صریحِ این هوک ─────────────────────────────────────────────────
 * فقط **ناوبریِ سطحِ مرورگر** را می‌گیرد: بستنِ تب، رفرش، رفتن به آدرسِ
 * دیگر.
 *
 * 🔴 ناوبریِ داخلِ برنامه (کلیک روی لینکِ منو) را **نمی‌گیرد**، و این
 * محدودیتِ معماری است نه فراموشی: `useBlocker` فقط با data routerِ
 * react-router کار می‌کند و این پروژه `<BrowserRouter>` دارد.
 *
 * ⚠️ مهاجرت به `createBrowserRouter` تغییرِ ساختاریِ بزرگی است و برای این
 * یک قابلیت توجیه ندارد. اگر روزی به دلایلِ دیگر انجام شد، همان‌جا این
 * هوک هم می‌تواند `useBlocker` را اضافه کند.
 *
 * ─── و چرا متنِ دلخواه نمی‌دهیم ────────────────────────────────────────────
 * مرورگرهای امروز پیامِ سفارشی را نادیده می‌گیرند و متنِ خودشان را نشان
 * می‌دهند. نوشتنِ متنِ فارسی اینجا فقط این توهم را می‌ساخت که کاربر آن را
 * می‌بیند.
 */
export function useUnsavedChanges(isDirty: boolean): void {
  useEffect(() => {
    if (!isDirty) return

    function warn(event: BeforeUnloadEvent) {
      event.preventDefault()

      // ⚠️ مرورگرهای قدیمی به مقدارِ بازگشتی نیاز دارند
      event.returnValue = ''
    }

    window.addEventListener('beforeunload', warn)

    return () => window.removeEventListener('beforeunload', warn)
  }, [isDirty])
}
