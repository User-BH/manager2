import { useQuery } from '@tanstack/react-query'
import { api } from '@/shared/lib/api'

/**
 * پرچم‌های قابلیت در سمتِ کلاینت (R44).
 *
 * ─── این لایه فقط برای رابطِ کاربری است، نه برای امنیت ──────────────────────
 * ⚠️ پنهان‌کردنِ دکمه هیچ چیزی را نمی‌بندد: تبِ بازِ کاربر، اسکریپت، و
 * نسخه‌ی کش‌شده‌ی فرانت هر سه بدونِ دیدنِ دکمه به همان مسیر می‌رسند. اجبارِ
 * واقعی در میان‌افزارِ `feature:` سمتِ سرور است و این هوک فقط کاری می‌کند
 * که کاربر به دری که بسته است نخورد.
 */

export type FeatureFlags = Record<string, boolean>

/**
 * ⚠️ پیش‌فرضِ ناشناخته `true` است، نه `false`.
 *
 * اگر درخواست شکست بخورد یا هنوز نیامده باشد، با `false` کلِ رابط تکه‌تکه
 * ناپدید می‌شود — کاربر یک صفحه‌ی نیمه‌خالی می‌بیند و فکر می‌کند سامانه
 * خراب است. با `true` رفتار همان چیزی می‌ماند که پیش از افزودنِ پرچم بود،
 * و اگر قابلیتی واقعاً خاموش باشد، سرور با ۴۰۳ و پیامِ روشن جوابش می‌دهد.
 */
const UNKNOWN_FLAG_DEFAULT = true

export function useFeatures() {
  const { data } = useQuery({
    queryKey: ['features'],
    queryFn: ({ signal }) => api<{ data: FeatureFlags }>('/features', { signal }),

    /*
     * ⚠️ پنجره‌ی کوتاه، و عمداً.
     *
     * کاربردِ اصلیِ این پرچم‌ها لحظه‌ی بحران است — «درگاه قطع شده، خاموشش
     * کن». اگر کش ساعتی بود، تبِ بازِ کاربر تا یک ساعت همچنان دکمه‌ی
     * پرداخت را نشان می‌داد. یک دقیقه به‌اندازه‌ی کافی کوتاه هست که تغییر
     * زود برسد، و به‌اندازه‌ی کافی بلند که هر ناوبری یک درخواستِ تازه
     * نسازد.
     */
    staleTime: 60_000,
    retry: 1,
  })

  const flags = data?.data

  return {
    flags,
    isEnabled: (flag: string): boolean => flags?.[flag] ?? UNKNOWN_FLAG_DEFAULT,
  }
}
