import { describe, expect, it } from 'vitest'

import { ApiError } from '@/shared/lib/apiError'
import { errorUx } from '@/shared/lib/errorUx'

/**
 * UXِ هر کدِ خطا (R69).
 *
 * ─── 🔴 چرا این تست‌ها لازم بودند ───────────────────────────────────────────
 * پیش از R69، `alertError` فقط ۴۰۲ را جدا می‌دید و بقیه — ۴۰۱، ۴۰۳، ۴۰۴،
 * ۴۰۹، ۴۲۹ و همه‌ی ۵xx — **یک دیالوگِ قرمزِ یکسان** می‌گرفتند.
 *
 * ⚠️ کاربر می‌فهمید «نشد» ولی نمی‌فهمید چه کند، در حالی که کارِ درست در
 * هر کدام فرق دارد: دوباره وارد شو / صفحه را تازه کن / چند ثانیه صبر کن /
 * چند دقیقه بعد برگرد.
 */

function apiError(status: number, message = 'پیامِ سرور', retryAfterMs?: number): ApiError {
  // ⚠️ ترتیب: (پیام، وضعیت، خطاهای فیلد، مهلتِ تلاشِ دوباره، شناسه‌ی پیگیری)
  return new ApiError(message, status, {}, retryAfterMs)
}

describe('نگاشتِ کدِ وضعیت به راهنمای کاربر', () => {
  /**
   * 🔴 مهم‌ترین ادعای این فایل: **هر** کدِ خواسته‌شده در برنامهٔ کار
   * راهنمای مخصوصِ خودش را دارد.
   *
   * ⚠️ سنجیدنِ «راهنما خالی نیست» کافی نیست؛ باید ثابت شود راهنماها با هم
   * **فرق دارند**، وگرنه یک متنِ عمومی برای همه هم از تور رد می‌شد.
   */
  it('هر کدِ خطا راهنمای متمایزِ خودش را می‌گیرد', () => {
    const codes = [0, 401, 403, 404, 409, 419, 429, 500, 502, 503]
    const hints = codes.map((code) => errorUx(apiError(code), 'خطا').hint)

    for (const [index, hint] of hints.entries()) {
      expect(hint, `کدِ ${codes[index]} راهنما ندارد`).not.toBe('')
    }

    expect(new Set(hints).size, 'دو کد راهنمای یکسان دارند').toBe(
      // ⚠️ ۵۰۲ و ۵۰۴ عمداً یک راهنما دارند (هر دو «سرور پاسخ نداد»)
      codes.length,
    )
  })

  it('۵۰۲ و ۵۰۴ عمداً یک راهنما دارند', () => {
    expect(errorUx(apiError(502), 'خطا').hint).toBe(errorUx(apiError(504), 'خطا').hint)
  })

  /** ⚠️ عنوان از سرور می‌آید، چون دقیق‌تر از هر متنِ عمومی است. */
  it('عنوان همان پیامِ سرور است', () => {
    expect(errorUx(apiError(403, 'شما به این بخش دسترسی ندارید.'), 'خطا').title).toBe(
      'شما به این بخش دسترسی ندارید.',
    )
  })

  it('اگر سرور پیامی نداد، متنِ جایگزین می‌نشیند', () => {
    expect(errorUx(apiError(500, ''), 'ذخیره نشد.').title).toBe('ذخیره نشد.')
  })

  // ── آیکون ────────────────────────────────────────────────────────────

  /**
   * ⚠️ آیکون بخشی از پیام است، نه تزئین.
   *
   * «دسترسی ندارید» خرابی نیست و آیکونِ قرمز آن را شبیهِ باگ نشان می‌دهد؛
   * «نشستتان تمام شد» هم اتفاقِ عادیِ زمان است.
   */
  it('نشستِ تمام‌شده خطا نیست', () => {
    expect(errorUx(apiError(401), 'خطا').icon).toBe('info')
    expect(errorUx(apiError(419), 'خطا').icon).toBe('info')
  })

  it('نبودِ دسترسی و نبودِ مورد، هشدارند نه خطا', () => {
    for (const status of [403, 404, 409, 429]) {
      expect(errorUx(apiError(status), 'خطا').icon, `کدِ ${status}`).toBe('warning')
    }
  })

  it('خرابیِ سرور واقعاً خطاست', () => {
    for (const status of [500, 502, 504]) {
      expect(errorUx(apiError(status), 'خطا').icon, `کدِ ${status}`).toBe('error')
    }
  })

  /** ⚠️ ۵۰۳ معمولاً به‌روزرسانیِ برنامه‌ریزی‌شده است، نه خرابی. */
  it('در دسترس نبودنِ موقت هشدار است', () => {
    expect(errorUx(apiError(503), 'خطا').icon).toBe('warning')
  })

  // ── ۴۲۹ و زمانِ انتظار ────────────────────────────────────────────────

  /**
   * 🔴 سرور هدرِ `Retry-After` می‌فرستد و لایهٔ تلاشِ دوباره از قبل
   * می‌خواندش — ولی **به کاربر گفته نمی‌شد**.
   *
   * «کمی صبر کنید» با «۹۰ ثانیه صبر کنید» یکی نیست: اولی یعنی کاربر هر
   * چند ثانیه دوباره می‌زند و سقف را تازه می‌کند.
   */
  it('زمانِ انتظارِ واقعی به کاربر گفته می‌شود', () => {
    expect(errorUx(apiError(429, 'زیاد تلاش شد', 90_000), 'خطا').hint).toContain('90 ثانیه')
  })

  it('کسری از ثانیه به بالا گرد می‌شود', () => {
    // ⚠️ «۰ ثانیه صبر کنید» راهنمایی نیست
    expect(errorUx(apiError(429, 'زیاد', 200), 'خطا').hint).toContain('1 ثانیه')
  })

  it('بدونِ هدرِ زمان، راهنمای عمومی می‌ماند', () => {
    const hint = errorUx(apiError(429), 'خطا').hint

    expect(hint).not.toContain('ثانیه صبر')
    expect(hint).not.toBe('')
  })

  // ── مرزها ────────────────────────────────────────────────────────────

  /** ⚠️ ۴۲۲ عمداً راهنما ندارد: خطاها زیرِ خودِ فیلد نشان داده می‌شوند. */
  it('خطای اعتبارسنجی راهنمای عمومی نمی‌گیرد', () => {
    expect(errorUx(apiError(422), 'خطا').hint).toBe('')
  })

  it('خطای غیرِ API به متنِ جایگزین می‌افتد', () => {
    expect(errorUx(new Error('چیزی شکست'), 'ذخیره نشد.').title).toBe('چیزی شکست')
    expect(errorUx('یک رشته', 'ذخیره نشد.').title).toBe('ذخیره نشد.')
    expect(errorUx(undefined, 'ذخیره نشد.').icon).toBe('error')
  })

  /** کدی که در نگاشت نیست نباید راهنمای گمراه‌کننده بدهد. */
  it('کدِ ناشناخته راهنمای ساختگی نمی‌سازد', () => {
    expect(errorUx(apiError(418), 'خطا').hint).toBe('')
  })
})
