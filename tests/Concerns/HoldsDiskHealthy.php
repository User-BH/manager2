<?php

namespace Tests\Concerns;

use App\Services\Health\DiskSpace;

/**
 * فضای دیسک را در تست روی مقدارِ سالم ثابت نگه می‌دارد (S4-27).
 *
 * ─── 🔴 این «خاموش‌کردنِ سنجه» نیست ────────────────────────────────────────
 * ⚠️ تفاوت ظریف ولی تعیین‌کننده است:
 *
 *   • تستی که **دربارهٔ دیسک** است → باید دیسکِ جعلی با درصدِ مشخص ببیند.
 *     آن کارِ `DiskThresholdTest` است و همان‌جا هر نُه آستانه سنجیده می‌شود.
 *
 *   • تستی که **دربارهٔ دیتابیس، کش، صف یا کدِ وضعیتِ مسیر** است → نباید
 *     نتیجه‌اش به پرشدنِ دیسکِ ماشین بستگی داشته باشد.
 *
 * 🔴 پیش از این، دستهٔ دوم هم دیسکِ واقعی را می‌دید. نتیجه‌اش این شد که با
 * رسیدنِ دیسکِ توسعه به ۹۸٪، پنج تست قرمز شدند که هیچ‌کدام ادعایی دربارهٔ
 * دیسک نداشتند — و با آزاد شدنِ فضا، بدونِ تغییرِ کد سبز شدند.
 *
 * ⚠️ اگر روزی این تریت جایی استفاده شود که واقعاً باید دیسک را بسنجد،
 * همان‌جا سنجه را کور می‌کند. پس فقط جایی که ادعای تست چیزِ دیگری است.
 */
trait HoldsDiskHealthy
{
    /** درصدِ اشغالی که مطمئناً زیرِ آستانهٔ هشدار است. */
    private const HEALTHY_DISK_PERCENT = 40;

    protected function holdDiskHealthy(): void
    {
        $this->app->instance(DiskSpace::class, new class extends DiskSpace
        {
            public function usage(string $path): ?array
            {
                $total = 1_000_000_000.0;

                return ['total' => $total, 'free' => $total * 0.6];
            }
        });
    }
}
