<?php

use Illuminate\Foundation\Inspiring;
use Illuminate\Support\Facades\Artisan;
use Illuminate\Support\Facades\Schedule;

Artisan::command('inspire', function () {
    $this->comment(Inspiring::quote());
})->purpose('Display an inspiring quote');

// یادآوریِ پیامکیِ قبوض عمداً حذف شده: طبق تصمیم، پیامک فقط برای کدِ
// یک‌بارمصرف (OTP) است و هیچ پیامکِ دیگری به کاربر فرستاده نمی‌شود.

/*
| یادآوریِ **درون‌برنامه‌ای** قبض‌های سررسیدشده (R22).
|
| همان قید بالا رعایت شده: این یادآوری فقط اعلانِ داخلِ سامانه است (زنگوله‌ی
| هدر)، نه پیامک. خودِ دستور فاصله‌ی حداقلیِ سه‌روزه و سقفِ چهار یادآوری را
| اعمال می‌کند، پس اجرای روزانه امن است و کسی روزی چند پیام نمی‌گیرد.
*/
Schedule::command('bills:remind')->dailyAt('09:00');

// اشتراک‌های سررسیدشده را منقضی و تراکنش‌های آنلاینِ رهاشده را می‌بندد
Schedule::command('subscriptions:maintain')->dailyAt('02:00');

// فایل‌های رسیدی که رکوردشان حذف شده (مثلاً با حذف آبشاریِ واحد) جمع می‌شوند
Schedule::command('receipts:prune')->weeklyOn(5, '03:00');

/*
| بکاپ‌ها سیاست نگه‌داری نداشتند و برای همیشه روی دیسک می‌ماندند. هر فایل یک
| کپی کامل از داده‌ی ساکنین است، پس انباشتنشان هم مسئله‌ی فضاست و هم حریم
| خصوصی. ده نسخه‌ی آخرِ هر مجتمع (و ده نسخه‌ی سیستمی) نگه داشته می‌شود.
*/
Schedule::command('backups:prune --keep=10')->weeklyOn(5, '03:30');

/*
| سندهای PDFِ تولیدشده (R28)
|
| هر دسته‌ی قبض یک فایلِ چندصد صفحه‌ای است و همه‌شان قابلِ بازتولیدند
| (پارامترهایشان ذخیره شده). دو هفته برای دانلود کافی است؛ رهاکردنشان همان
| مشکلِ انباشتِ بکاپ‌ها را تکرار می‌کند.
*/
Schedule::command('documents:prune --days=14')->weeklyOn(5, '03:15');

// دستگاه‌های مورداعتمادِ منقضی‌شده‌ی «مرا به خاطر بسپار»
Schedule::command('trusted-devices:prune')->dailyAt('03:45');

/*
| سنجه‌های کارایی (R38): هر بازدید تا پنج ردیف می‌سازد و این جدول سقفِ
| طبیعی ندارد. ۹۰ روز سه برابرِ پنجره‌ی ۲۸ روزه‌ی گوگل است، پس روند هم
| دیده می‌شود.
*/
Schedule::command('web-vitals:prune')->weeklyOn(5, '03:50');

/*
| نگه‌داریِ صف (R11)
|
| `failed_jobs` خودش هرگز پاک نمی‌شود. اگر رهایش کنیم، جدولی که کسی نگاهش
| نمی‌کند بی‌نهایت بزرگ می‌شود — و چون هر ردیفش بدنه‌ی کاملِ Job را دارد،
| سریع‌تر از انتظار رشد می‌کند. دو هفته برای بررسی کافی است.
*/
Schedule::command('queue:prune-failed --hours=336')->weeklyOn(6, '04:00');

// دسته‌های ناتمامِ صف هم همین‌طور
Schedule::command('queue:prune-batches --hours=336')->weeklyOn(6, '04:15');
