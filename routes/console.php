<?php

use Illuminate\Foundation\Inspiring;
use Illuminate\Support\Facades\Artisan;
use Illuminate\Support\Facades\Schedule;

Artisan::command('inspire', function () {
    $this->comment(Inspiring::quote());
})->purpose('Display an inspiring quote');

// یادآوریِ پیامکیِ قبوض عمداً حذف شده: طبق تصمیم، پیامک فقط برای کدِ
// یک‌بارمصرف (OTP) است و هیچ پیامکِ دیگری به کاربر فرستاده نمی‌شود.

/*
| یادآوریِ **درون‌برنامه‌ای** قبض‌های سررسیدشده (R22).
|
| همان قید بالا رعایت شده: این یادآوری فقط اعلانِ داخلِ سامانه است (زنگوله‌ی
| هدر)، نه پیامک. خودِ دستور فاصله‌ی حداقلیِ سه‌روزه و سقفِ چهار یادآوری را
| اعمال می‌کند، پس اجرای روزانه امن است و کسی روزی چند پیام نمی‌گیرد.
*/
Schedule::command('bills:remind')->dailyAt('09:00');

// اشتراک‌های سررسیدشده را منقضی و تراکنش‌های آنلاینِ رهاشده را می‌بندد
Schedule::command('subscriptions:maintain')->dailyAt('02:00');

/*
| پرداخت‌هایی که سرنوشتشان دانسته نشد (R59).
|
| ⚠️ پس از R59، پرداختی که درگاه در موردش پاسخ نداد دیگر «ناموفق» نمی‌شود
| و `pending` می‌ماند — چون نمی‌دانیم پول کسر شده یا نه. ولی ردیفی که
| هیچ‌کس نبیندش، از ردیفِ اشتباهاً ناموفق بهتر نیست.
|
| ساعتِ ۸:۳۰ صبح عمدی است: خروجی باید وقتی برسد که آدمی هست تا در پنلِ
| بانک پیگیری کند، نه نیمه‌شب.
*/
Schedule::command('payments:stale')->dailyAt('08:30');

// فایل‌های رسیدی که رکوردشان حذف شده (مثلاً با حذف آبشاریِ واحد) جمع می‌شوند
Schedule::command('receipts:prune')->weeklyOn(5, '03:00');

/*
| بکاپ‌ها سیاست نگه‌داری نداشتند و برای همیشه روی دیسک می‌ماندند. هر فایل یک
| کپی کامل از داده‌ی ساکنین است، پس انباشتنشان هم مسئله‌ی فضاست و هم حریم
| خصوصی. ده نسخه‌ی آخرِ هر مجتمع (و ده نسخه‌ی سیستمی) نگه داشته می‌شود.
*/
Schedule::command('backups:prune --keep=10')->weeklyOn(5, '03:30');

/*
| سندهای PDFِ تولیدشده (R28)
|
| هر دسته‌ی قبض یک فایلِ چندصد صفحه‌ای است و همه‌شان قابلِ بازتولیدند
| (پارامترهایشان ذخیره شده). دو هفته برای دانلود کافی است؛ رهاکردنشان همان
| مشکلِ انباشتِ بکاپ‌ها را تکرار می‌کند.
*/
Schedule::command('documents:prune --days=14')->weeklyOn(5, '03:15');

// دستگاه‌های مورداعتمادِ منقضی‌شده‌ی «مرا به خاطر بسپار»
Schedule::command('trusted-devices:prune')->dailyAt('03:45');

/*
| سنجه‌های کارایی (R38): هر بازدید تا پنج ردیف می‌سازد و این جدول سقفِ
| طبیعی ندارد. ۹۰ روز سه برابرِ پنجره‌ی ۲۸ روزه‌ی گوگل است، پس روند هم
| دیده می‌شود.
*/
Schedule::command('web-vitals:prune')->weeklyOn(5, '03:50');

/*
| نگه‌داریِ صف (R11)
|
| `failed_jobs` خودش هرگز پاک نمی‌شود. اگر رهایش کنیم، جدولی که کسی نگاهش
| نمی‌کند بی‌نهایت بزرگ می‌شود — و چون هر ردیفش بدنه‌ی کاملِ Job را دارد،
| سریع‌تر از انتظار رشد می‌کند. دو هفته برای بررسی کافی است.
*/
Schedule::command('queue:prune-failed --hours=336')->weeklyOn(6, '04:00');

// دسته‌های ناتمامِ صف هم همین‌طور
Schedule::command('queue:prune-batches --hours=336')->weeklyOn(6, '04:15');

/*
|--------------------------------------------------------------------------
| سلامت، هشدار و بکاپِ خودکار (R43)
|--------------------------------------------------------------------------
*/

/*
| ضربانِ زمان‌بند.
|
| ⚠️ سبک‌ترین کارِ این فایل و مهم‌ترینش: خاموش‌بودنِ cron هیچ نشانه‌ای بیرون
| نمی‌دهد — نه خطایی، نه ۵۰۰ای — و می‌تواند ماه‌ها دیده نشود. این یک خط
| نوشتن در کش، تنها ردی است که مسیرِ `/up` می‌تواند از آن بفهمد زمان‌بند
| زنده است.
|
| `withoutOverlapping` ندارد چون کارش کسری از ثانیه است و قفل‌گرفتن برایش
| گران‌تر از خودِ کار می‌شد.
*/
Schedule::command('health:heartbeat')->everyFiveMinutes();

/*
| سنجشِ سلامت و اعلامِ مشکل.
|
| ⚠️ این نمی‌تواند مرگِ خودِ زمان‌بند را بگیرد — اگر cron نباشد، این هم اجرا
| نمی‌شود. آن یکی را فقط پایشِ بیرونی می‌گیرد که به `/up` می‌زند. هر دو مسیر
| لازم است و هیچ‌کدام جای دیگری را نمی‌گیرد.
|
| `--quiet-when-ok` یعنی وقتی همه‌چیز سالم است هیچ خروجی‌ای نیست؛ وگرنه cron
| هر پانزده دقیقه یک ایمیلِ «همه‌چیز خوب است» می‌ساخت و آدم‌ها یاد می‌گرفتند
| خروجیِ این cron را نخوانند — درست همان عادتی که روزِ خرابی گران تمام
| می‌شود.
*/
Schedule::command('health:check --quiet-when-ok')
    ->everyFifteenMinutes()
    ->withoutOverlapping();

/*
| بکاپِ خودکارِ روزانه.
|
| ⚠️ تا پیش از این، بکاپ فقط با فشردنِ دکمه در پنل ساخته می‌شد — یعنی
| سامانه هر جمعه بکاپ‌های قدیمی را هرس می‌کرد ولی هرگز بکاپِ تازه‌ای
| نمی‌ساخت.
|
| ساعتِ ۰۱:۳۰ عمداً پیش از `backups:prune` جمعه‌هاست (۰۳:۳۰): اول نسخه‌ی
| تازه ساخته شود، بعد هرس. برعکسش یعنی در بدترین لحظه، هرس اجرا شود و
| نسخه‌ی جایگزینش هنوز ساخته نشده باشد.
*/
Schedule::command('backups:run')
    ->dailyAt('01:30')
    ->withoutOverlapping();

/*
| آرشیوِ فایل‌های آپلودی (R58).
|
| 🔴 تا پیش از این، بکاپ فقط **دیتابیس** بود: ردیفِ `receipt_path` برمی‌گشت
| و خودِ رسید — تنها سندِ پرداختِ ساکن — هیچ نسخه‌ی دومی نداشت.
|
| ⚠️ **هفتگی، نه روزانه** — و این یک سازش است، نه غفلت. هر آرشیو کپیِ
| کاملِ همه‌ی فایل‌هاست (نه افزایشی)، پس گرفتنِ روزانه‌اش همان گیگابایت‌ها
| را هر شب دوباره روی دیسک می‌نشاند. هزینه‌اش در `config/backup.php` با
| `rpo_files_hours` صریح اعلام شده و `backups:verify` همان عدد را می‌سنجد.
|
| ساعتِ ۰۱:۴۵ عمداً پس از بکاپِ دیتابیس (۰۱:۳۰) و پیش از هرس (۰۳:۳۰) است.
*/
Schedule::command('backups:files')
    ->weeklyOn(5, '01:45')
    ->withoutOverlapping();

/*
| انتقال به مقصدِ خارج از سرور (R58).
|
| 🔴 مهم‌ترین شکافِ این مرحله: همه‌ی بکاپ‌ها روی همان دیسکی بودند که خودِ
| داده روی آن است. در برابرِ «اشتباهی پاک شد» کار می‌کرد و در برابرِ «سرور
| مُرد» هیچ.
|
| ⚠️ اگر `BACKUP_OFFSITE_DISK` تنظیم نشده باشد، این دستور هشدار می‌دهد و
| **خطا نمی‌دهد**. عمدی است: خطای هرشبه‌ی یک تنظیمِ انجام‌نشده ظرفِ یک هفته
| باعث می‌شود کسی خروجیِ cron را نخواند — و آن‌وقت خطاهای واقعی هم دیده
| نشوند. `backups:verify` هفتگی همین را برجسته گزارش می‌کند.
|
| ساعتِ ۰۲:۱۵: بکاپِ ۰۱:۳۰ در صف ساخته می‌شود و این فاصله به کارگرِ صف
| فرصت می‌دهد. اگر عقب بماند، تازه‌ترین نسخه‌ی *آماده* منتقل می‌شود و
| فردا نسخه‌ی امروز — و `backups:verify` عقب‌ماندگیِ ماندگار را می‌گیرد.
*/
Schedule::command('backups:offsite')
    ->dailyAt('02:15')
    ->withoutOverlapping();

/*
| تمرینِ دوره‌ایِ بازیابی (R58).
|
| ⚠️ داشتنِ فایلِ بکاپ با **قابلِ بازیابی بودنش** یکی نیست. بکاپ سه‌جور
| بی‌صدا می‌میرد: `APP_KEY` عوض می‌شود، schema جلو می‌رود، یا زمان‌بند
| خاموش می‌ماند. هر سه تا روزِ حادثه نامرئی‌اند.
|
| شنبه ۰۵:۰۰، پس از همه‌ی کارهای شبانه: آنچه می‌سنجد نتیجه‌ی همان‌هاست.
*/
Schedule::command('backups:verify')
    ->weeklyOn(6, '05:00')
    ->withoutOverlapping();

/*
| سیاستِ نگه‌داریِ داده (R45).
|
| ⚠️ پنج جدولِ پرترافیک هیچ سیاستی نداشتند و بی‌مرز رشد می‌کردند —
| بدترینشان `otp_codes` (یک ردیف به‌ازای هر تلاشِ ورود) و `sessions` (که در
| هر درخواست خوانده و نوشته می‌شود و لاراول خودش پاکش نمی‌کند).
|
| ساعتِ ۰۴:۳۰ عمداً پس از بکاپِ ۰۱:۳۰ است: اگر قاعده‌ای روزی اشتباه تنظیم
| شود و چیزی را پاک کند که نباید، بکاپِ همان شب **پیش از** حذف گرفته شده
| است.
*/
Schedule::command('data:prune')
    ->dailyAt('04:30')
    ->withoutOverlapping();
